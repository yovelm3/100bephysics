def fig():
    g = Fig(560, 300, "גרף מהירות-זמן: עולה ל-10 מטר לשנייה ב-5 שניות, קבועה עד 8, יורדת קווית ל-5- ב-20 שניות, ועולה ל-0 ב-25 שניות")
    X, Y = g.graph(70, 270, 420, 220, "t (s)", "v (m/s)", xticks=[(t, str(t)) for t in (5, 10, 15, 20, 25)], yticks=[(-5, "-5"), (5, "5"), (10, "10")], xmax=27, ymin=-6, ymax=11)
