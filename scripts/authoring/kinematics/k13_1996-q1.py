def agraph():
    g = Fig(560, 300, "גרף התשובה: תאוצה כפונקציה של הזמן. מדרגות: 2 מטר לשנייה בריבוע עד 5 שניות, אפס עד 8 שניות, מינוס 1.25 עד 20 שניות, ו-1 עד 25 שניות")
    X, Y = g.graph(70, 220, 420, 190, "t (s)", "a (m/s²)", xticks=[(t, str(t)) for t in (5, 8, 20, 25)],
                   yticks=[(-1.25, "-1.25"), (1, "1"), (2, "2")], xmax=27, ymin=-1.8, ymax=2.4)
    for a, b, v in ((0, 5, 2), (5, 8, 0), (8, 20, -1.25), (20, 25, 1)):
        g.plot(X, Y, [(a, v), (b, v)], width=3.4)
    for x in (5, 8, 20):
        g.line(X(x), Y(-1.8), X(x), Y(2.4), stroke="var(--d-dim)", width=1, dash="4 3")
    return g

