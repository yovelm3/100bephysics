        S(r"$8 < t < 16\,\text{s}$", r"מהירות חיובית ויורדת", r"v \rightarrow,\quad a \leftarrow,\quad \textstyle\sum F \leftarrow"),
        S(r"$16 < t < 20\,\text{s}$", r"מהירות שלילית שגדלה בגודלה", r"v \leftarrow,\quad a \leftarrow,\quad \textstyle\sum F \leftarrow"),
        S(r"$20 < t < 25\,\text{s}$", r"מהירות שלילית שחוזרת לאפס", r"v \leftarrow,\quad a \rightarrow,\quad \textstyle\sum F \rightarrow"),
