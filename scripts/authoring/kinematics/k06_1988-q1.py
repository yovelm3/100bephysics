from mk import *

def fig():
    g = Fig(560, 330, "גרף מהירות-זמן: מ-2 ל-4 מטר לשנייה עד 2 שניות, קבועה עד 5 שניות, יורדת ל-6- ב-10 שניות, ועולה ל-1 ב-17 שניות")
    X, Y = g.graph(70, 300, 440, 270, "t (s)", "v (m/s)", xticks=[(t, str(t)) for t in range(2, 23, 2)],
                   yticks=[(v, str(v)) for v in range(-6, 5) if v != 0], xmax=22, ymin=-6, ymax=4)
    g.plot(X, Y, [(0, 2), (2, 4), (5, 4), (10, -6), (17, 1)])
    return g

