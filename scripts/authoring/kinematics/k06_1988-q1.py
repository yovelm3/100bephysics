def agraph():
    g = Fig(560, 320, "גרף התשובה: תאוצה כפונקציה של הזמן. מדרגות אופקיות: 1 מטר לשנייה בריבוע עד 2 שניות, אפס עד 5 שניות, מינוס 2 עד 10 שניות, ו-1 עד 17 שניות")
    X, Y = g.graph(70, 250, 430, 200, "t (s)", "a (m/s²)", xticks=[(t, f"{t:g}") for t in (2, 5, 10, 17)],
                   yticks=[(v, f"{v:g}") for v in (-2, -1, 1)], xmax=18, ymin=-2.5, ymax=1.6)
    for a, b, v in ((0, 2, 1), (2, 5, 0), (5, 10, -2), (10, 17, 1)):
        g.plot(X, Y, [(a, v), (b, v)], width=3.4)
    for x in (2, 5, 10):
        g.line(X(x), Y(-2.5), X(x), Y(1.6), stroke="var(--d-dim)", width=1, dash="4 3")
    return g

