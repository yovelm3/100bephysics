from mk import *
STRICT["on"] = True
T = [0, 0.08, 0.16, 0.24, 0.32, 0.4, 0.48]
Y_ = [0.016, 0.150, 0.430, 0.810, 1.400, 2.000, 2.840]
vc = lambda i: (Y_[i + 1] - Y_[i - 1]) / 0.16
pts = [(T[i], vc(i)) for i in range(1, 6)]
n = len(pts); tm = sum(p[0] for p in pts) / n; vm = sum(p[1] for p in pts) / n
slope = sum((p[0] - tm) * (p[1] - vm) for p in pts) / sum((p[0] - tm) ** 2 for p in pts)

def fig():
    g = Fig(560, 110, "טבלה: מקום הגוף y במטרים בזמנים 0 עד 0.48 שניות, ושורה ריקה למהירויות")
    x0, y0 = 20, 15
    g.rect(x0, y0, 520, 84, fill="none", width=1.5)
    for r in (28, 56):
        g.line(x0, y0 + r, x0 + 520, y0 + r, width=1.2)
    g.line(x0 + 72, y0, x0 + 72, y0 + 84, width=1.2)
    g.text(x0 + 36, y0 + 20, "t (s)"); g.text(x0 + 36, y0 + 48, "y (m)"); g.text(x0 + 36, y0 + 76, "v (m/s)")
    for i, (t, y) in enumerate(zip(T, Y_)):
        cx = x0 + 72 + 32 + i * 64
        g.text(cx, y0 + 20, f"{t:g}", cls="dim"); g.text(cx, y0 + 48, f"{y:.3f}", cls="dim")
    return g

b0 = vm - slope * tm

def scatter():
    g = Fig(560, 310, "גרף התשובה: חמש נקודות של מהירות כפונקציה של הזמן, מ-2.59 מטר לשנייה אחרי 0.08 שניות ועד 9 אחרי 0.4 שניות, וקו מגמה ישר שעובר קרוב לכולן")
    X, Y = g.graph(70, 270, 420, 220, "t (s)", "v (m/s)", xticks=[(t, f"{t:g}") for t in (0.08, 0.16, 0.24, 0.32, 0.4)], yticks=[(v, str(v)) for v in (2, 4, 6, 8, 10)], xmax=0.46, ymax=10.5)
    g.plot(X, Y, [(0, b0), (0.45, b0 + slope * 0.45)], stroke="var(--d-ask)", dash="7 5")
    for t, v in pts:
        g.circle(X(t), Y(v), 5.5, fill="var(--d-label)")
    g.heb(X(0.44), Y(b0 + slope * 0.44) + 22, "קו מגמה", anchor="end")
    return g

