def fig():
    g = Fig(560, 225, "שוטר על אופנוע עומד בצד כביש ישר. מכונית חולפת על פניו במהירות קבועה של 108 קמ\"ש. כשהמכונית במרחק 87.5 מטר ממנו, השוטר יוצא לדרך בתאוצה קבועה של 4 מטר לשנייה בריבוע")
    g.ground(20, 540, 150); g.heb(90, 182, "שוטר על אופנוע"); g.heb(420, 182, "מכונית")
    g.line(20, 120, 540, 120, stroke="var(--d-hatch)", width=2, dash="14 10")
    g.motorcycle(90, 150, 72)
    g.text(90, 70, "a = 4 m/s²")
    g.car(420, 150, 80, None)
    g.arrow(468, 120, 520, 120, "108 km/h", lx=494, ly=108)
    g.dim(90, 200, 420, 200, "87.5 m", offset=0)
    return g

def vgraph():
    g = Fig(560, 320, "גרף התשובה: מהירות כפונקציה של הזמן. המכונית: קו אופקי ב-30 מטר לשנייה. האופנוע: קו ישר שעולה מאפס עד 70 מטר לשנייה אחרי 17.5 שניות. הקווים נחתכים אחרי 7.5 שניות")
    X, Y = g.graph(70, 280, 420, 230, "t (s)", "v (m/s)", xticks=[(t, f"{t:g}") for t in (5, 7.5, 10, 15, 17.5)], yticks=[(v, str(v)) for v in (10, 30, 50, 70)], xmax=19, ymax=76)
    g.plot(X, Y, [(0, 30), (17.5, 30)], stroke="var(--d-label)")
    g.plot(X, Y, [(0, 0), (17.5, 70)])
    g.guide(X, Y, 7.5, 30)
    g.heb(X(17.5) + 4, Y(30) - 10, "מכונית", anchor="end")
    g.heb(X(17.5) - 14, Y(70) + 6, "אופנוע", anchor="end")
    return g

