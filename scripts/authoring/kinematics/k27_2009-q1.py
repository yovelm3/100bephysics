def fig():
    g = Fig(560, 280, "בניין בגובה 45 מטר. כדור A נזרק מהגג כלפי מעלה במהירות 40 מטר לשנייה, וכדור B נזרק מרגלי הבניין כלפי מעלה במהירות 55 מטר לשנייה")
    g.ground(80, 480, 250)
    g.rect(200, 100, 50, 150)
    g.dim(180, 100, 180, 250, "45 m")
    g.ball(262, 92, 8); g.text(262, 122, "A")
    g.arrow(262, 80, 262, 30, "40 m/s", lx=274, ly=50, anchor="start")
    g.ball(330, 241, 8); g.text(346, 246, "B", anchor="start")
    g.arrow(330, 229, 330, 170, "55 m/s", lx=342, ly=196, anchor="start")
    return g

def relgraph():
    g = Fig(560, 280, "גרף התשובה: המקום של כדור A לפי הציר שצמוד לכדור B, כפונקציה של הזמן. קו ישר יורד מ-45 מטר ברגע אפס, עד אפס אחרי 3 שניות")
    X, Y = g.graph(70, 240, 420, 190, "t (s)", "y*_A (m)", xticks=[(t, str(t)) for t in (1, 2, 3)], yticks=[(v, str(v)) for v in (15, 30, 45)], xmax=3.4, ymax=50)
    g.plot(X, Y, [(0, 45), (3, 0)])
    return g

