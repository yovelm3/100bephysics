    g.rect(x0, y0, 500, 80, fill="none", width=1.5); g.line(x0, y0 + 40, x0 + 500, y0 + 40, width=1.2); g.line(x0 + 60, y0, x0 + 60, y0 + 80, width=1.2)
    g.text(x0 + 30, y0 + 26, "t (s)"); g.text(x0 + 30, y0 + 66, "s (m)")
    for i, (t, s) in enumerate(zip(T, S_)):
        cx = x0 + 60 + 22 + i * 44
        g.text(cx, y0 + 26, f"{t:g}", cls="dim"); g.text(cx, y0 + 66, f"{s:g}", cls="dim")
    g.path("M 60,160 C 160,170 230,220 300,250 S 450,290 520,290", stroke="var(--d-line)", width=3)
    g.circle(80, 156, 7); g.heb(80, 140, "יעל")
    g.heb(300, 200, "מגלשה (מבט על)")
    return g

