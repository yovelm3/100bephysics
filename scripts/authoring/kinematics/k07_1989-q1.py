def fig():
    g = Fig(560, 320, "לוח משופע ABCD בזווית 30 מעלות לאופק. נקודה E נמצאת 2.5 מטר מעל הצלע DA ו-1.5 מטר מהצלע CD. הכדור נזרק מ-E במקביל ל-BC, לכיוון הצלע CD")
    D = (70, 270); u = (70, 0); w = (44, -54)
    Pt = lambda a, b: (D[0] + a * u[0] + b * w[0], D[1] + a * u[1] + b * w[1])
    A, B, C = Pt(4.2, 0), Pt(4.2, 3.6), Pt(0, 3.6)
    g.poly([D, A, B, C])
    Bf = (B[0], A[1])
    g.poly([A, Bf, B], fill="none", width=1.5, dash="5 4")
    g.angle(A[0], A[1], 40, 0, 50.8, "30°", lr=56)
    for p, t, dx, dy in [(D, "D", -12, 16), (A, "A", 0, 20), (B, "B", 10, -6), (C, "C", -12, -6)]:
        g.text(p[0] + dx, p[1] + dy, t)
    E_ = Pt(1.5, 2.5)
    F_ = Pt(1.5, 0); G_ = Pt(0, 2.5)
    g.line(*E_, *F_, stroke="var(--d-dim)", width=1.2, dash="4 3")
    g.text((E_[0] + F_[0]) / 2 + 30, (E_[1] + F_[1]) / 2 + 8, "2.5 m", cls="dim")
    g.dim(G_[0], G_[1] + 16, E_[0], E_[1] + 16, "1.5 m", offset=0, side=-1)
    g.line(*G_, G_[0], G_[1] + 20, stroke="var(--d-dim)", width=1, dash="3 3"); g.line(*E_, E_[0], E_[1] + 20, stroke="var(--d-dim)", width=1, dash="3 3")
    g.ball(*E_, r=7)
    g.text(E_[0] + 10, E_[1] - 6, "E", anchor="start")
    g.arrow(E_[0] - 6, E_[1] - 16, E_[0] - 60, E_[1] - 16, "v₀", lx=E_[0] - 33, ly=E_[1] - 24)
    g.heb(330, 308, "הכדור נזרק במקביל לצלע BC")
    return g

