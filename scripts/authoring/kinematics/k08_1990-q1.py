from mk import *

def fig():
    g = Fig(560, 300, "כדור על קצה גג בניין בגובה 5 מטר נזרק אופקית במהירות v0")
    g.ground(0, 560, 250)
    g.rect(110, 90, 90, 160)
    for y in (120, 155, 190, 225):
        g.line(122, y, 188, y, width=1.2, stroke="var(--d-hatch)")
    g.ball(194, 81, 9, "m = 0.1 kg", ldx=0, ldy=-18)
    g.arrow(206, 81, 272, 81, "v₀ = 5 m/s", lx=278, ly=85, anchor="start")
    g.dim(85, 90, 85, 250, "5 m")
    return g

