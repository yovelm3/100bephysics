XS = [0, 0.5, 1.2, 2.1, 3.2, 4.5, 6.0, 7.7]

def fig():
    g = Fig(560, 170, "סרט נייר עם שמונה נקודות, מ-M עד N. מקומות הנקודות: 0, 0.5, 1.2, 2.1, 3.2, 4.5, 6.0, 7.7 סנטימטר. הנקודה החמישית אחרי M מסומנת A")
    x0, s = 30, 62
    g.rect(x0, 40, 8.2 * s, 30, fill="var(--d-fill)", width=1.5)
    for i, x in enumerate(XS):
        g.add(f'<rect x="{x0 + x * s - 4:.1f}" y="51" width="8" height="8" transform="rotate(45 {x0 + x * s:.1f} 55)" fill="var(--d-label)"/>')
    for lab, x in (("M", 0), ("A", 4.5), ("N", 7.7)):
        g.text(x0 + x * s, 32, lab)
    g.line(x0, 90, x0 + 8 * s, 90, width=1.5)
    for k in range(0, 81):
        L = 14 if k % 10 == 0 else 8
        g.line(x0 + k / 10 * s, 90, x0 + k / 10 * s, 90 + L, width=1 if k % 10 else 1.6)
    for k in range(9):
        g.text(x0 + k * s, 124, str(k), cls="dim")
    g.text(x0 + 8 * s, 150, "x (cm)", cls="dim", anchor="end")
    return g

