from mk import *

def fig():
    g = Fig(560, 320, "גרף מהירות-זמן של מעלית בשבעה קטעים A עד G, כיוון חיובי כלפי מעלה")
    X, Y = g.graph(70, 290, 420, 250, "t (s)", "v (m/s)", xticks=[(5, "5"), (10, "10"), (15, "15")], yticks=[(v, str(v)) for v in (-2, -1, 1, 2, 3)], xmax=17, ymin=-3, ymax=3, grid=False)
    g.plot(X, Y, [(0, 0), (3, 3), (6, 3), (7, 0), (10, 0), (11, -2), (14, -2), (17, 0)])
    for t in (3, 6, 11, 14):
        g.line(X(t), Y(0), X(t), Y(3 if t < 10 else -2), stroke="var(--d-dim)", width=1, dash="4 3")
    for t in range(1, 17):
        g.line(X(t), Y(0) - 3, X(t), Y(0) + 3, stroke="var(--d-line)", width=1)
    for t, v, s in [(1.2, 1.9, "A"), (4.5, 3.35, "B"), (6.9, 1.4, "C"), (8.5, -0.5, "D"), (10.2, -1.3, "E"), (12.5, -2.45, "F"), (16, -1.3, "G")]:
        g.text(X(t), Y(v), s)
    return g

