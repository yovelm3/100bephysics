def fig():
    g = Fig(560, 300, "גרף א: מהירות מכונית א' מ-0 ל-6 מטר לשנייה ב-10 שניות, עולה ל-10 ב-50 שניות וקבועה עד 60. גרף ב: מהירות מכונית ב' מ-0 ל-2 ב-10 שניות ול-10 ב-30 שניות")
    for k, (ox, pts, title) in enumerate([(50, [(0, 0), (10, 6), (50, 10), (60, 10)], "גרף א (מכונית א')"), (320, [(0, 0), (10, 2), (30, 10)], "גרף ב (מכונית ב')")]):
        X, Y = g.graph(ox, 240, 200, 180, "t (s)", "v (m/s)", xticks=[(t, str(t)) for t in (10, 20, 30, 40, 50, 60)], yticks=[(v, str(v)) for v in (2, 4, 6, 8, 10, 12, 14, 16)], xmax=70, ymax=16)
        g.plot(X, Y, pts)
        g.heb(ox + 100, 288, title)
    return g

def agraph():
    g = Fig(560, 280, "גרף התשובה: תאוצת מכונית א' כפונקציה של הזמן. מדרגות: 0.6 מטר לשנייה בריבוע עד 10 שניות, 0.1 עד 50 שניות, ואפס עד 60 שניות")
    X, Y = g.graph(70, 240, 420, 190, "t (s)", "a (m/s²)", xticks=[(t, str(t)) for t in (10, 20, 30, 40, 50, 60)], yticks=[(v, f"{v:g}") for v in (0.1, 0.2, 0.4, 0.6)], xmax=64, ymax=0.7)
    for a, b, v in ((0, 10, 0.6), (10, 50, 0.1), (50, 60, 0)):
        g.plot(X, Y, [(a, v), (b, v)], width=3.4)
    for x in (10, 50):
        g.line(X(x), Y(0), X(x), Y(0.7), stroke="var(--d-dim)", width=1, dash="4 3")
    return g

