from mk import *

T = [0, 0.02, 0.04, 0.06, 0.08, 0.10, 0.12]
Xm = [0, 0.009, 0.020, 0.033, 0.048, 0.065, 0.084]
vc = lambda i: (Xm[i + 1] - Xm[i - 1]) / (T[i + 1] - T[i - 1])

def fig():
    g = Fig(560, 330, "טבלת מקום-זמן של קרונית במישור משופע, וארבעה גרפים אפשריים של מהירות-זמן (I עד IV), וקרונית שיורדת במסלול עקום")
    x0, y0 = 20, 20
    g.rect(x0, y0, 520, 52, fill="none", width=1.5); g.line(x0, y0 + 26, x0 + 520, y0 + 26, width=1.2)
    g.line(x0 + 72, y0, x0 + 72, y0 + 52, width=1.2)
    g.text(x0 + 36, y0 + 18, "t (s)"); g.text(x0 + 36, y0 + 44, "x (m)")
    for i, (t, x) in enumerate(zip(T, Xm)):
        cx = x0 + 72 + 32 + i * 64
        g.text(cx, y0 + 18, f"{t:g}", cls="dim"); g.text(cx, y0 + 44, f"{x:g}", cls="dim")
    shapes = {"I": lambda u: u, "II": lambda u: 1 - (1 - u) ** 2.2, "III": lambda u: 0.15 + 0.85 * (1 - u) ** 2.4, "IV": lambda u: u ** 2.2}
    for k, (lab, fn) in enumerate(shapes.items()):
        ox = 30 + (k % 2) * 150; oy = 180 + (k // 2) * 130
        g.line(ox, oy, ox + 110, oy, width=1.5); g.line(ox, oy, ox, oy - 90, width=1.5)
        g.text(ox - 8, oy - 84, "v", cls="dim"); g.text(ox + 112, oy + 14, "t", cls="dim")
        g.path("M " + " L ".join(f"{ox + 100 * i / 30:.1f},{oy - 80 * fn(i / 30):.1f}" for i in range(31)), stroke="var(--d-body)", width=2.2)
        g.text(ox + 70, oy - 60, lab)
    g.path("M 360,110 Q 380,250 520,300", stroke="var(--d-line)", width=3)
    g.block(368, 128, 18, 12, angle=-80)
    g.heb(450, 320, "מסלול עקום (סעיף ה)")
    return g

