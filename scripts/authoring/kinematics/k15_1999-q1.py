T = [0, 0.02, 0.04, 0.06, 0.08, 0.10, 0.12]
Xm = [0, 0.009, 0.020, 0.033, 0.048, 0.065, 0.084]
vc = lambda i: (Xm[i + 1] - Xm[i - 1]) / (T[i + 1] - T[i - 1])

P0, P1, P2 = (60, 120), (190, 352), (620, 352)   # the curved track: steep at the top, almost flat at the bottom

def bez(u):
    """Point and slope angle (degrees, screen) on the track; u in [0, 1]."""
    x = (1 - u) ** 2 * P0[0] + 2 * (1 - u) * u * P1[0] + u * u * P2[0]
    y = (1 - u) ** 2 * P0[1] + 2 * (1 - u) * u * P1[1] + u * u * P2[1]
    dx = 2 * (1 - u) * (P1[0] - P0[0]) + 2 * u * (P2[0] - P1[0])
    dy = 2 * (1 - u) * (P1[1] - P0[1]) + 2 * u * (P2[1] - P1[1])
    return x, y, math.degrees(math.atan2(dy, dx))

def cart(g, u, cid="cart"):
    """A cart standing on the track at parameter u: one group (id) rotated to the track, ready to be moved along it."""
    x, y, ang = bez(u)
    g.add(f'<g id="{cid}" transform="translate({x:.1f} {y:.1f}) rotate({ang:.1f})">'
          '<rect x="-38" y="-44" width="76" height="30" rx="5" fill="var(--d-body)" stroke="var(--d-line)" stroke-width="1.6"/>'
          '<rect x="-30" y="-39" width="22" height="13" rx="2" fill="#ffffff" opacity="0.35"/>'
          '<circle cx="-22" cy="-10" r="10" fill="var(--d-label)"/><circle cx="22" cy="-10" r="10" fill="var(--d-label)"/>'
          '<circle cx="-22" cy="-10" r="3.5" fill="#ffffff"/><circle cx="22" cy="-10" r="3.5" fill="#ffffff"/></g>')

def fig():
    g = Fig(660, 600, "למעלה: טבלת מקום-זמן של קרונית במישור משופע. באמצע: קרונית שעומדת בראש מסלול עקום בלי חיכוך. המסלול תלול בהתחלה ונעשה כמעט אופקי בתחתית. למטה: ארבעה גרפים אפשריים של גודל המהירות כפונקציה של הזמן, I עד IV")
    # the table
    x0, y0, cw = 20, 16, 80
    g.rect(x0, y0, 620, 56, fill="none", width=1.5); g.line(x0, y0 + 28, x0 + 620, y0 + 28, width=1.2)
    g.line(x0 + 60, y0, x0 + 60, y0 + 56, width=1.2)
    g.text(x0 + 30, y0 + 19, "t (s)"); g.text(x0 + 30, y0 + 47, "x (m)")
    for i, (t, x) in enumerate(zip(T, Xm)):
        cx = x0 + 60 + cw / 2 + i * cw
        if i: g.line(x0 + 60 + i * cw, y0, x0 + 60 + i * cw, y0 + 56, stroke="var(--d-hatch)", width=1)
        g.text(cx, y0 + 19, f"{t:g}", cls="dim"); g.text(cx, y0 + 47, f"{x:g}", cls="dim")
    # the curved track (part ה), with a support underneath so it reads as a solid track
    d = f"M {P0[0]},{P0[1]} Q {P1[0]},{P1[1]} {P2[0]},{P2[1]}"
    g.add(f'<path d="{d} L {P2[0]},366 L {P0[0]},366 Z" fill="var(--d-fill)" stroke="none"/>')
    g.add(f'<path id="track" d="{d}" fill="none" stroke="var(--d-line)" stroke-width="3.5"/>')
    g.ground(30, 640, 366)
    cart(g, 0.07)
    g.heb(150, 118, "יוצאת ממנוחה", anchor="start")
    g.heb(470, 318, "מסלול עקום, בלי חיכוך (סעיף ה)")
    # the four answer graphs, in one row
    shapes = {"I": lambda u: u, "II": lambda u: 1 - (1 - u) ** 2.2, "III": lambda u: 0.15 + 0.85 * (1 - u) ** 2.4, "IV": lambda u: u ** 2.2}
    for k, (lab, fn) in enumerate(shapes.items()):
        ox = 40 + k * 158; oy = 560
        g.line(ox, oy, ox + 118, oy, width=1.6); g.line(ox, oy, ox, oy - 120, width=1.6)
        g.text(ox - 8, oy - 112, "v", cls="dim"); g.text(ox + 122, oy + 15, "t", cls="dim")
        g.path("M " + " L ".join(f"{ox + 108 * i / 30:.1f},{oy - 104 * fn(i / 30):.1f}" for i in range(31)), stroke="var(--d-body)", width=2.6)
        g.text(ox + 59, oy + 30, lab)
    return g

