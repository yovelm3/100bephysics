from mk import *

def fig():
    g = Fig(560, 170, "מיקומי שתי משאיות בהפרשי זמן שווים לאורך הקטע MN. משאית A: חמישה מרווחים, שניים מ-M עד P ושלושה מ-P עד N. משאית B: שישה מרווחים שווים")
    s = 380 / 180
    x0 = 110
    for row, (lab, ks) in enumerate([("משאית A", [0, 45.5, 90, 133.6, 149.8, 180]), ("משאית B", [0, 30, 60, 90, 120, 150, 180])]):
        y = 50 + row * 80
        g.line(x0 - 10, y, x0 + 180 * s + 10, y, width=1.6)
        for k in ks:
            g.circle(x0 + k * s, y, 5, fill="var(--d-label)")
        for t, k in (("M", 0), ("P", 90), ("N", 180)):
            g.text(x0 + k * s, y + 22, t)
        g.heb(x0 - 20, y + 5, lab, anchor="end")
    return g

