from mk import *
STRICT["on"] = True

def fig():
    g = Fig(560, 300, "גרף מקום-זמן של שתי סירות: סירה ב בקו ישר עד 3 קילומטר ב-150 שניות ואחר כך בעקומה שמתמתנת עד 4 קילומטר ב-230 שניות; סירה א בקו ישר עד 1 קילומטר ב-150 שניות ואחר כך בקו ישר תלול עד 4 קילומטר ב-230 שניות")
    X, Y = g.graph(70, 260, 420, 210, "t (s)", "x (km)", xticks=[(t, str(t)) for t in (50, 100, 150, 200, 250)], yticks=[(v, str(v)) for v in (1, 2, 3, 4)], xmax=250, ymax=4.3)
    g.plot(X, Y, [(0, 0), (150, 3)])
    g.curve(X, Y, lambda t: (3000 + 20 * (t - 150) - 0.09375 * (t - 150) ** 2) / 1000, 150, 230)
    g.plot(X, Y, [(0, 0), (150, 1), (230, 4)], dash="6 4", stroke="var(--d-line)")
    g.line(X(230), Y(4), X(230), Y(0), stroke="var(--d-dim)", width=1, dash="8 5")
    g.heb(X(110), Y(2.6), "ב"); g.heb(X(180), Y(1.7), "א")
    return g

def vgraph():
    g = Fig(560, 300, "גרף התשובה: מהירות סירה ב כפונקציה של הזמן. קו אופקי ב-20 מטר לשנייה עד 150 שניות, ואחר כך קו ישר יורד עד 5 מטר לשנייה אחרי 230 שניות")
    X, Y = g.graph(70, 260, 420, 210, "t (s)", "v (m/s)", xticks=[(t, str(t)) for t in (50, 100, 150, 200, 230)], yticks=[(v, str(v)) for v in (5, 10, 15, 20)], xmax=250, ymax=23)
    g.plot(X, Y, [(0, 20), (150, 20), (230, 5)])
    g.guide(X, Y, 230, 5)
    g.text(X(230) + 8, Y(5) - 8, "5 m/s", cls="dim", anchor="start")
    return g

