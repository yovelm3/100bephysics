from mk import *

T = [0, 0.02, 0.04, 0.06, 0.08, 0.10, 0.12, 0.14, 0.16, 0.18, 0.20, 0.22]
Xcm = [0, 1.20, 2.88, 5.04, 7.68, 10.8, 14.4, 18.48, 23.04, 28.08, 33.60, 39.60]
vc = lambda i: (Xcm[i + 1] - Xcm[i - 1]) / 100 / (T[i + 1] - T[i - 1])  # central difference, m/s

def fig():
    g = Fig(560, 330, "טבלת מקום-זמן של גוף, מ-0 עד 0.22 שניות, וגרף המקום כפונקציה של הזמן")
    g.rect(20, 20, 150, 24 + 12 * 22, fill="none", width=1.5)
    g.line(95, 20, 95, 44 + 12 * 22, width=1.2); g.line(20, 44, 170, 44, width=1.2)
    g.text(57, 37, "t (s)"); g.text(132, 37, "x (cm)")
    for i, (t, x) in enumerate(zip(T, Xcm)):
        y = 44 + 22 * i + 16
        g.text(57, y, f"{t:g}", cls="dim"); g.text(132, y, f"{x:g}", cls="dim")
    X, Y = g.graph(240, 300, 270, 240, "t (s)", "x (cm)", xticks=[(t, f"{t:g}") for t in (0.04, 0.08, 0.12, 0.16, 0.2)], yticks=[(v, str(v)) for v in (10, 20, 30, 40)], xmax=0.24, ymax=45)
    g.curve(X, Y, lambda t: 48 * t + 600 * t * t, 0, 0.23)
    for t, x in zip(T, Xcm):
        g.dot(X(t), Y(x), 2.6)
    return g

