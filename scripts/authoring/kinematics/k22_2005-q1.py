    g.text(148, 24, "y", anchor="start")
    g.heb(80, 212, "יוסי")
    vs = [("1", dict(pts=[(0, 0.8), (0.5, 0), (1, 0.8)])), ("2", dict(pts=[(0, 0.8), (1, -0.8)], neg=True)), ("3", dict(pts=[(0, 0), (0.5, 0.8), (1, 0)])),
          ("4", dict(fn=lambda u: 0.55 * (1 - (1 - 2 * u) ** 2) if u < 0.5 else 0.55 + 0.35 * (2 * u - 1) ** 2))]
    for i, (lab, kw) in enumerate(vs):
        mini(g, 250 + i * 78, 90 if lab != "2" else 70, 58, 50 if lab != "2" else 40, label=lab, yl="v", **kw)
    ys = [("5", dict(fn=lambda u: 0.55 * (1 - (1 - 2 * u) ** 2) if u < 0.5 else 0.55 + 0.4 * (2 * u - 1) ** 2)), ("6", dict(pts=[(0, 0), (0.5, 0.8), (1, 0)])),
          ("7", dict(fn=lambda u: 3.2 * u * (1 - u))), ("8", dict(neg=True, segs=[(lambda u: 1.6 * u * (1 - u) * 1.6, 0, 0.45), (lambda u: -1.8 * (u - 0.55) ** 2 * 2.2, 0.55, 1)]))]
    for i, (lab, kw) in enumerate(ys):
        mini(g, 250 + i * 78, 210 if lab != "8" else 196, 58, 50 if lab != "8" else 36, label=lab, yl="y", **kw)
    return g

