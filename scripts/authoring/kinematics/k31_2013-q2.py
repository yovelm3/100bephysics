def vgraph():
    g = Fig(560, 300, "גרף התשובה: מהירות הגוף כפונקציה של הזמן. עקומה שיוצאת מהראשית בשיפוע תלול ומתמתנת, ומתקרבת לקו אופקי מקווקו ב-20 מטר לשנייה. אין מספרים על ציר הזמן")
    X, Y = g.graph(70, 260, 420, 210, "t", "v (m/s)", yticks=[(20, "20")], xmax=6, ymax=23)
    g.plot(X, Y, [(0, 20), (6, 20)], stroke="var(--d-dim)", dash="6 4", width=1.6)
    g.curve(X, Y, lambda t: 20 * math.tanh(t / 2), 0, 6)
    g.plot(X, Y, [(0, 0), (2.1, 21)], stroke="var(--d-ask)", dash="5 4", width=1.8)
    g.heb(X(2.2), Y(21.5), "שיפוע g בהתחלה", anchor="start")
    return g

def body_fbd(f_size, note):
    return lambda: fbd([("mg", -90, 1.2), ("f", 90, f_size)],
        "תרשים כוחות על הגוף בזמן הנפילה: כוח הכובד mg כלפי מטה, וכוח החיכוך עם האוויר f כלפי מעלה. " + note + ". הכיוון החיובי כלפי מטה, כיוון התנועה",
        positive=-90, body="ball", note=note)

