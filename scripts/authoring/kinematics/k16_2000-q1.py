def fig():
    g = Fig(560, 320, "בניין בגובה 300 מטר. כדור א נזרק מרגלי הבניין כלפי מעלה במהירות 40 מטר לשנייה, ובאותו רגע כדור ב נזרק מהגג כלפי מטה במהירות 20 מטר לשנייה. ציר y כלפי מעלה, ראשיתו בקרקע")
    g.ground(60, 520, 290)
    g.rect(230, 40, 80, 250)
    g.dim(200, 40, 200, 290, "300 m")
    g.ball(330, 52, 9); g.text(346, 48, "ב", anchor="start")
    g.arrow(330, 64, 330, 110, "20 m/s", lx=342, ly=96, anchor="start")
    g.ball(330, 278, 9); g.text(346, 284, "א", anchor="start")
    g.arrow(330, 266, 330, 220, "40 m/s", lx=342, ly=236, anchor="start")
    g.add('<line x1="90" y1="290" x2="90" y2="22" stroke="var(--d-line)" stroke-width="1.8" marker-end="url(#f-axis)"/>')
    g.text(98, 26, "y", anchor="start"); g.text(80, 296, "0", anchor="end")
    return g

def dgraph():
    g = Fig(560, 300, "גרף התשובה: המרחק בין הכדורים כפונקציה של הזמן. קו ישר יורד מ-300 מטר ברגע אפס, עד אפס אחרי 5 שניות")
    X, Y = g.graph(70, 260, 420, 220, "t (s)", "d (m)", xticks=[(t, str(t)) for t in range(1, 6)], yticks=[(v, str(v)) for v in (60, 120, 180, 240, 300)], xmax=5.6, ymax=320)
    g.plot(X, Y, [(0, 300), (5, 0)])
    return g

