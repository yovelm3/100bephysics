def fig():
    g = Fig(560, 330, "גרף המקום האנכי של כדור כפונקציה של הזמן: פרבולה מ-40 מטר ב-0 שניות (נקודה A), שיא 45 מטר ב-1 שנייה (B), 25 מטר ב-3 שניות (C), ו-0 ב-4 שניות (D)")
    X, Y = g.graph(80, 300, 400, 260, "t (s)", "y (m)", xticks=[(t, str(t)) for t in range(1, 5)], yticks=[(v, str(v)) for v in range(5, 46, 5)], xmax=4.8, ymax=48)
    g.curve(X, Y, lambda t: 40 + 10 * t - 5 * t * t, 0, 4)
    for t, lab in ((0, "A"), (1, "B"), (3, "C"), (4, "D")):
        y = 40 + 10 * t - 5 * t * t
        g.dot(X(t), Y(y)); g.text(X(t) + 10, Y(y) - 8, lab, anchor="start")
    return g

def vgraph():
    g = Fig(560, 320, "גרף התשובה: מהירות הכדור כפונקציה של הזמן. קו ישר יורד מ-10 מטר לשנייה ברגע אפס עד מינוס 30 אחרי 4 שניות. מסומנות הנקודות a ברגע 0 (10), b ברגע 1 (אפס), c ברגע 3 (מינוס 20), ו-d ברגע 4 (מינוס 30)")
    X, Y = g.graph(70, 280, 420, 240, "t (s)", "v (m/s)", xticks=[(t, str(t)) for t in range(1, 5)], yticks=[(v, str(v)) for v in (-30, -20, -10, 10)], xmax=4.6, ymin=-33, ymax=13)
    g.plot(X, Y, [(0, 10), (4, -30)])
    for t, lab, dx, dy in ((0, "a", 14, 16), (1, "b", 6, -12), (3, "c", 12, -4), (4, "d", 12, 4)):
        v = 10 - 10 * t
        g.circle(X(t), Y(v), 5.5, fill="var(--d-ask)")
        g.text(X(t) + dx, Y(v) + dy, lab, anchor="start")
    return g

