    for t, lab in ((0, "A"), (1, "B"), (3, "C"), (4, "D")):
        y = 40 + 10 * t - 5 * t * t
        g.dot(X(t), Y(y)); g.text(X(t) + 10, Y(y) - 8, lab, anchor="start")
    return g

