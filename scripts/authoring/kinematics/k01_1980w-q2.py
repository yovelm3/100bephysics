from mk import *

def fig():
    g = Fig(560, 300, "גרף מהירות-זמן: 500 מטר לשנייה עד 0.02 שניות, ירידה קווית ל-100 מטר לשנייה ב-0.022 שניות, ואחר כך קבועה")
    X, Y = g.graph(70, 250, 420, 200, "t (s)", "v (m/s)", xticks=[(0.01, "0.01"), (0.02, "0.02"), (0.03, "0.03")],
                   yticks=[(100, "100"), (200, "200"), (300, "300"), (400, "400"), (500, "500")], xmax=0.03, ymax=500)
    g.plot(X, Y, [(0, 500), (0.02, 500), (0.022, 100), (0.03, 100)])
    g.line(X(0.02), Y(500), X(0.02), Y(0), stroke="var(--d-dim)", width=1, dash="4 3")
    g.line(X(0.022), Y(100), X(0.022), Y(0), stroke="var(--d-dim)", width=1, dash="4 3")
    g.text(X(0.022) + 4, Y(0) - 6, "0.022", cls="dim", anchor="start")
    return g

