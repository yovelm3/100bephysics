import math

def v(t):
    if t < 20: return 50 * math.tanh(t / 5)
    if t < 21.2: return 50 - (t - 20) / 1.2 * 40
    if t < 55: return 4 + 6 * math.exp(-(t - 21.2) / 0.35)
    return 0

def fig():
    g = Fig(560, 300, "גרף מהירות-זמן של צנחן: המהירות עולה בעקומה עד 50 מטר לשנייה בערך ב-13 שניות, קבועה עד 20 שניות, יורדת בחדות לכ-4 מטר לשנייה עד 22.5 שניות, קבועה עד 55 שניות, ואז אפס")
    X, Y = g.graph(60, 270, 440, 220, "t (s)", "v (m/s)", xticks=[(t, str(t)) for t in range(5, 61, 5)], yticks=[(v_, str(v_)) for v_ in range(10, 61, 10)], xmax=60, ymax=60)
    pts = [(i / 10, v(i / 10)) for i in range(0, 550)] + [(55, 4), (55, 0), (60, 0)]
    g.plot(X, Y, pts)
    return g

