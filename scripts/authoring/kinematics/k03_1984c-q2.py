from mk import *

def fig():
    g = Fig(560, 270, "למעלה: גרף תאוצה-זמן עם תאוצה חיובית קבועה, אחר כך אפס, ואחר כך תאוצה שלילית קבועה. למטה: ארבעה גרפים של מקום-זמן, א עד ד")
    X, Y = g.graph(150, 100, 280, 70, "t", "a", xmax=3, ymin=-1, ymax=1, grid=False)
    g.plot(X, Y, [(0, 0.6), (1, 0.6)]); g.plot(X, Y, [(1, 0), (2, 0)]); g.plot(X, Y, [(2, -0.6), (3, -0.6)])
    g.line(X(1), Y(0.6), X(1), Y(0), stroke="var(--d-dim)", width=1, dash="4 3")
    g.line(X(2), Y(0), X(2), Y(-0.6), stroke="var(--d-dim)", width=1, dash="4 3")
    g.line(X(3), Y(0), X(3), Y(-0.6), stroke="var(--d-dim)", width=1, dash="4 3")
    w, h, top = 100, 70, 160
    opts = [
        ("א", [(0, 0), (0.33, 0.08), (0.5, 0.25), (0.67, 0.6), (0.85, 0.85), (1, 0.92)], "s"),
        ("ב", None, "b"),
        ("ג", None, "c"),
        ("ד", [(0, 0), (0.3, 0.6), (0.7, 0.6), (1, 0)], None),
    ]
    for i, (lab, pts, kind) in enumerate(reversed(opts)):
        ox = 30 + i * 135
        x0, y0 = ox, top + h
        g.line(x0, y0, x0 + w + 8, y0, width=1.5); g.line(x0, y0, x0, y0 - h - 8, width=1.5)
        g.text(x0 + w + 14, y0 + 4, "t", cls="dim", anchor="start"); g.text(x0, y0 - h - 12, "x", cls="dim")
        P_ = lambda a, b: (x0 + a * w, y0 - b * h)
        if lab == "א":
            g.path("M %s,%s Q %s,%s %s,%s L %s,%s Q %s,%s %s,%s" % (*P_(0, 0), *P_(0.25, 0), *P_(0.35, 0.18), *P_(0.65, 0.66), *P_(0.8, 0.9), *P_(1, 0.92)), stroke="var(--d-body)", width=2.4)
            g.line(*P_(0.35, 0.18), *P_(0.35, 0), stroke="var(--d-dim)", width=1, dash="3 3"); g.line(*P_(0.65, 0.66), *P_(0.65, 0), stroke="var(--d-dim)", width=1, dash="3 3")
        elif lab == "ב":
            g.path("M %s,%s Q %s,%s %s,%s" % (*P_(0, 0), *P_(0.25, 0), *P_(0.33, 0.55)), stroke="var(--d-body)", width=2.4)
            g.line(*P_(0.33, 0.55), *P_(0.33, 0), stroke="var(--d-dim)", width=1, dash="3 3")
            g.line(*P_(0.33, 0), *P_(0.67, 0), stroke="var(--d-body)", width=2.4)
            g.line(*P_(0.67, 0.55), *P_(0.67, 0), stroke="var(--d-dim)", width=1, dash="3 3")
            g.path("M %s,%s Q %s,%s %s,%s" % (*P_(0.67, 0.55), *P_(0.75, 0), *P_(1, 0)), stroke="var(--d-body)", width=2.4)
        elif lab == "ג":
            g.path("M %s,%s Q %s,%s %s,%s L %s,%s Q %s,%s %s,%s" % (*P_(0, 0), *P_(0.25, 0), *P_(0.33, 0.6), *P_(0.67, 0.6), *P_(0.75, 0), *P_(1, 0)), stroke="var(--d-body)", width=2.4)
        else:
            g.poly([P_(a, b) for a, b in pts], close=False, stroke="var(--d-body)", width=2.4)
        g.heb(x0 + w / 2, y0 + 22, lab)
    return g

