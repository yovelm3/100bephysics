from mk import *

def fig():
    g = Fig(560, 330, "גרף מהירות-זמן של טיל: עלייה קווית ל-180 מטר לשנייה ב-10 שניות, ואחר כך ירידה קווית שחוצה את האפס ב-100 שניות וממשיכה לערכים שליליים")
    X, Y = g.graph(70, 290, 420, 250, "t (s)", "v (m/s)", xticks=[(10, "10"), (100, "100")], yticks=[(180, "180")], xmax=200, ymin=-180, ymax=180, grid=False)
    g.plot(X, Y, [(0, 0), (10, 180), (190, -180)])
    g.guide(X, Y, 10, 180)
    return g

