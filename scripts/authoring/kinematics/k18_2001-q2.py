from mk import *

def fig():
    g = Fig(560, 320, "כדור פורח עולה במהירות 5 מטר לשנייה ונסחף אופקית במהירות 4.5 מטר לשנייה. אבן משתחררת מתחתית הסל בנקודה A, בגובה 4 מטר מעל הנקודה P שעל הקרקע, ופוגעת בקרקע בנקודה Q")
    g.ground(40, 520, 290)
    g.circle(200, 80, 55, fill="var(--d-fill)", stroke="var(--d-line)")
    g.line(168, 124, 186, 160, width=1.5); g.line(232, 124, 214, 160, width=1.5)
    g.rect(186, 160, 28, 22)
    g.dot(200, 190); g.text(212, 196, "A", anchor="start")
    g.dim(150, 190, 150, 290, "4 m")
    g.arrow(110, 140, 110, 90, "5 m/s", lx=100, ly=120, anchor="end")
    g.arrow(270, 110, 330, 110, "4.5 m/s", lx=300, ly=100)
    g.text(200, 312, "P"); g.dot(200, 290, 3); g.text(420, 312, "Q"); g.dot(420, 290, 3)
    return g

