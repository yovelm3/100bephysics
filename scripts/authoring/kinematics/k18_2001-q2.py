def fig():
    g = Fig(560, 320, "כדור פורח עולה במהירות 5 מטר לשנייה ונסחף אופקית במהירות 4.5 מטר לשנייה. אבן משתחררת מתחתית הסל בנקודה A, בגובה 4 מטר מעל הנקודה P שעל הקרקע, ופוגעת בקרקע בנקודה Q")
    g.ground(40, 520, 290)
    g.circle(200, 80, 55, fill="var(--d-fill)", stroke="var(--d-line)")
    g.line(168, 124, 186, 160, width=1.5); g.line(232, 124, 214, 160, width=1.5)
    g.rect(186, 160, 28, 22)
    g.dot(200, 190); g.text(212, 196, "A", anchor="start")
    g.dim(150, 190, 150, 290, "4 m")
    g.arrow(110, 140, 110, 90, "5 m/s", lx=100, ly=120, anchor="end")
    g.arrow(270, 110, 330, 110, "4.5 m/s", lx=300, ly=100)
    g.text(200, 312, "P"); g.dot(200, 290, 3); g.text(420, 312, "Q"); g.dot(420, 290, 3)
    return g

TQ = (5 + 105 ** 0.5) / 10   # flight time of the stone

def path_fig():
    g = Fig(560, 320, "תרשים התשובה: מסלול האבן. האבן יוצאת מהנקודה A, בגובה 4 מטר מעל הנקודה P, עולה עוד 1.25 מטר, ואז יורדת בקשת של פרבולה עד הנקודה Q שעל הקרקע, מימין ל-P")
    X = lambda m: 90 + m * 52
    Y = lambda m: 270 - m * 40
    g.ground(30, 540, Y(0))
    pts = [(4.5 * t, 4 + 5 * t - 5 * t * t) for t in [TQ * k / 40 for k in range(41)]]
    g.path("M " + " L ".join(f"{X(a):.1f},{Y(b):.1f}" for a, b in pts), stroke="var(--d-body)", width=3, dash="7 5")
    g.dot(X(0), Y(4)); g.text(X(0) + 10, Y(4) + 18, "A", anchor="start")
    g.dot(X(0), Y(0)); g.text(X(0), Y(0) + 22, "P")
    q = 4.5 * TQ
    g.dot(X(q), Y(0)); g.text(X(q), Y(0) + 22, "Q")
    g.line(X(0), Y(0), X(0), Y(4), stroke="var(--d-dim)", width=1, dash="4 3")
    g.dim(X(0) - 40, Y(0), X(0) - 40, Y(4), "4 m", side=-1)
    g.line(X(0), Y(5.25), X(0.45 * 4.5 + 0.3), Y(5.25), stroke="var(--d-dim)", width=1, dash="4 3")
    g.dim(X(0) - 40, Y(4), X(0) - 40, Y(5.25), "1.25 m", side=-1, label_dx=-8)
    g.arrow(X(0), Y(4), X(0) + 4.5 * 9, Y(4) - 5 * 9, color="var(--d-ask)", width=2.2)
    g.heb(X(q) - 10, Y(5.6), "מסלול האבן: פרבולה", anchor="end")
    return g

