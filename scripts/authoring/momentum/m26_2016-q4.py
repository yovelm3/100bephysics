from mk import *

def fig():
    g = Fig(560, 300, "תרשים 1: תיבה m נעה ימינה לעבר תיבה M במנוחה. תרשים 2: גרף המהירות של שתי התיבות כפונקציה של הזמן באלפיות שנייה: m יורדת מ-2 ל-1.2- בין 1 ל-3 אלפיות שנייה, ו-M עולה מאפס ל-0.8")
    X, Y = g.graph(70, 220, 360, 190, "t (ms)", "v (m/s)", xticks=[(t, f"{t:g}") for t in (0.5, 1, 1.5, 2, 2.5, 3, 3.5)], yticks=[(v, f"{v:g}") for v in (-1.5, -1, -0.5, 0.5, 1, 1.5, 2, 2.5)], xmax=3.6, ymin=-1.6, ymax=2.6)
    g.plot(X, Y, [(0, 2), (1.05, 2), (2.95, -1.2), (3.5, -1.2)])
    g.plot(X, Y, [(0, 0), (0.95, 0), (2.9, 0.8), (3.5, 0.8)], stroke="var(--d-line)")
    g.text(X(3.45), Y(0.8) - 8, "M"); g.text(X(3.45), Y(-1.2) + 18, "m")
    g.ground(450, 550, 60, depth=6); g.block(470, 46, 20, 20, "m"); g.arrow(484, 40, 506, 40, None); g.block(530, 46, 24, 24, "M")
    return g

