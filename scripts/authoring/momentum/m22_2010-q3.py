from mk import *
import math

def fig():
    g = Fig(560, 230, "תרשים I: גודל הכוח על הדסקית הפוגעת כפונקציה של הזמן, פעמון בגובה של 4 משבצות. תרשים II: שלושה פעמונים A, B, C בגבהים שונים, B בגובה של 4 משבצות")
    def bell(X, Y, h, c=0.0):
        return [(t, h * math.exp(-((t - 2.5) / 0.55) ** 2)) for t in [1.2 + i * 0.05 for i in range(53)]]
    X, Y = g.graph(310, 190, 200, 140, "t", "F₂", xmax=4, ymax=6, grid=False)
    for v in range(1, 6): g.line(X(0), Y(v), X(4), Y(v), stroke="var(--d-hatch)", width=0.7)
    for h, lab in ((5.6, "A"), (4, "B"), (2.8, "C")):
        g.plot(X, Y, bell(X, Y, h), width=1.8); g.text(X(2.5), Y(h) + 16, lab, cls="dim")
    g.heb(410, 222, "תרשים II")
    X, Y = g.graph(50, 190, 200, 140, "t", "F₁", xmax=4, ymax=6, grid=False)
    for v in range(1, 6): g.line(X(0), Y(v), X(4), Y(v), stroke="var(--d-hatch)", width=0.7)
    g.plot(X, Y, bell(X, Y, 4), width=1.8)
    g.heb(150, 222, "תרשים I")
    return g

