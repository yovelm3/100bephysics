from mk import *

def fig():
    g = Fig(560, 170, "קרונית במסה 80 קילוגרם נעה ימינה במהירות 3 מטר לשנייה על מסילה חלקה. אדם במסה 60 קילוגרם רץ אחריה במהירות 8 מטר לשנייה")
    g.ground(30, 530, 140)
    g.poly([(260, 80), (400, 80), (390, 126), (270, 126)], fill="var(--d-fill)")
    for x in (290, 370): g.circle(x, 130, 10, fill="var(--d-label)")
    g.arrow(410, 100, 470, 100, "V₁ = 3 m/s", lx=476, ly=104, anchor="start")
    g.person(150, 140, 1.4); g.arrow(175, 90, 225, 90, "v = 8 m/s", lx=200, ly=80)
    return g

