from mk import *

def panel(g, ox, oy, title, vecs, extra=None):
    s = 16
    for i in range(13): g.line(ox + i * s, oy, ox + i * s, oy + 12 * s, stroke="var(--d-hatch)", width=0.7)
    for j in range(13): g.line(ox, oy + j * s, ox + 12 * s, oy + j * s, stroke="var(--d-hatch)", width=0.7)
    g.rect(ox, oy, 12 * s, 12 * s, fill="none", width=1.2)
    for (px, py, dx, dy, lab) in vecs:
        x0, y0 = ox + px * s, oy + (12 - py) * s
        g.circle(x0, y0, 4, fill="var(--d-label)"); g.text(x0 + 7, y0 + 4, lab, cls="dim", anchor="start")
        g.arrow(x0, y0, x0 + dx * s, y0 - dy * s, None, width=1.8)
    if extra: extra(ox, oy, s)
    g.heb(ox + 6 * s, oy + 12 * s + 20, title)

