def fig():
    g = Fig(560, 210, "קרונית ועליה ארובה אנכית, ובקרקעית הארובה קפיץ. תרשים א: הקפיץ רפוי. תרשים ב: כדור במסה 40 גרם מכווץ את הקפיץ ב-10 סנטימטר")
    for ox, comp, lab in ((300, False, "תרשים א"), (40, True, "תרשים ב")):
        g.rect(ox, 100, 200, 60, fill="none")
        for x in (ox + 30, ox + 170): g.circle(x, 168, 9, fill="var(--d-body)")
        g.line(ox + 80, 20, ox + 80, 160, width=1.5); g.line(ox + 120, 20, ox + 120, 160, width=1.5)
        top = 70 if comp else 30
        g.spring(ox + 100, 160, ox + 100, top, coils=6 if comp else 9, amp=14)
        if comp:
            g.circle(ox + 100, top - 14, 14); g.dim(ox + 140, 30, ox + 140, 70, "10 cm", offset=0)
        g.heb(ox + 100, 200, lab)
    return g

