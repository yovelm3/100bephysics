def fig():
    g = Fig(560, 200, "שני גופים במסה 1 קילוגרם כל אחד, מחוברים בקפיץ מכווץ, מחליקים על משטח חלק. אחרי שחרור הקפיץ אחד נע בכיוון x ב-3 מטר לשנייה והשני בכיוון y ב-4 מטר לשנייה")
    g.add('<line x1="60" y1="170" x2="250" y2="170" stroke="var(--d-line)" stroke-width="1.6" marker-end="url(#f-axis)"/>'); g.add('<line x1="60" y1="170" x2="60" y2="20" stroke="var(--d-line)" stroke-width="1.6" marker-end="url(#f-axis)"/>')
    g.text(256, 174, "x", anchor="start"); g.text(66, 26, "y", anchor="start")
    g.block(110, 120, 30, 30, "m"); g.spring(125, 120, 165, 120, coils=4); g.block(180, 120, 30, 30, "m")
    g.arrow(205, 90, 245, 60, "v₀ ?", lx=250, ly=58, anchor="start")
