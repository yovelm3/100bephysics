def fig():
    g = Fig(560, 200, "קפיץ A מחובר לקיר, ונער מושך אותו בכוח של 20 ניוטון. הקפיץ מתארך ב-0.4 מטר")
    g.wall(60, 40, 160); g.spring(60, 100, 300, 100, coils=12)
    g.arrow(300, 100, 380, 100, "F = 20 N", lx=390, ly=104, anchor="start")
    g.dim(220, 140, 300, 140, "0.4 m", offset=0); g.text(180, 80, "A")
    return g

def hooke_fig():
    g = Fig(420, 260, "גרף הכוח כפונקציה של ההתארכות: קו ישר מהראשית עד 20 ניוטון בהתארכות של 0.4 מטר. השטח מתחת לקו הוא משולש")
    X, Y = g.graph(70, 220, 300, 180, "Δℓ (m)", "F (N)", xticks=[(0.1, "0.1"), (0.2, "0.2"), (0.3, "0.3"), (0.4, "0.4")], yticks=[(5, "5"), (10, "10"), (15, "15"), (20, "20")], xmax=0.46, ymax=23)
    g.poly([(X(0), Y(0)), (X(0.4), Y(20)), (X(0.4), Y(0))], fill="var(--d-fill)", stroke="none", width=0)
    g.plot(X, Y, [(0, 0), (0.4, 20)])
    g.line(X(0.4), Y(20), X(0.4), Y(0), stroke="var(--d-dim)", width=1, dash="3 3")
    return g

