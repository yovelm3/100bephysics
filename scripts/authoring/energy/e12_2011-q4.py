    g.block(96, 40, 16, 10, None, angle=-55); g.text(80, 22, "A")
    g.text(200, 168, "B"); g.text(270, 168, "C"); g.dot(400, 100); g.text(410, 98, "D", anchor="start")
    g.dim(60, 30, 60, 150, "HA", offset=0)
