from mk import *
HA = [0.6, 0.7, 0.8, 0.9, 1.2]; VD = [1.45, 2.00, 2.50, 2.80, 3.75]
V2 = [v * v for v in VD]
n = 5; xm = sum(HA) / n; ym = sum(V2) / n
slope = sum((x - xm) * (y - ym) for x, y in zip(HA, V2)) / sum((x - xm) ** 2 for x in HA)
x0 = xm - ym / slope

