from mk import *

def fig():
    g = Fig(560, 240, "גרף הכוח F כפונקציה של מהירות הגוף v: 8 ניוטון עד 8 מטר לשנייה, 5 ניוטון עד 16, ו-2.5 ניוטון עד 20")
    X, Y = g.graph(100, 210, 360, 170, "v (m/s)", "F (N)", xticks=[(8, "8"), (16, "16"), (20, "20")], yticks=[(2.5, "2.5"), (5, "5"), (8, "8")], xmax=22, ymax=9)
    g.plot(X, Y, [(0, 8), (8, 8)]); g.plot(X, Y, [(8, 5), (16, 5)]); g.plot(X, Y, [(16, 2.5), (20, 2.5)])
    for v, f in ((8, 8), (16, 5), (20, 2.5)): g.line(X(v), Y(f), X(v), Y(0), stroke="var(--d-dim)", width=1, dash="3 3")
    return g

