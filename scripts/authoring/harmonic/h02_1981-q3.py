    g.line(cx, cy, bx, by, width=1.8); g.ball(bx, by, r=9); g.text(bx + 18, by + 4, "m", anchor="start")
    g.angle(cx, cy, 50, -90, -76, "θ", lr=64)
    g.text(cx + 34, cy + 110, "ℓ", anchor="start")
    return g

