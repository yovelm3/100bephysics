import math
g0 = 10; L = 1; m = 0.1; th = math.radians(5)
T = 2 * math.pi * math.sqrt(L / g0); tq = T / 4
v = math.sqrt(2 * g0 * L * (1 - math.cos(th)))
Tmax = m * g0 + m * v ** 2 / L
T2 = 2 * T

