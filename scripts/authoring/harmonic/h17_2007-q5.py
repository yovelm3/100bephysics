T = 12; vmax = 0.10; w = 2 * math.pi / T; A = vmax / w

def fig():
    g = Fig(560, 260, "גרף המהירות v בסנטימטר לשנייה כפונקציה של הזמן t בשניות: מתחיל באפס, מקסימום 10 ב-3 שניות, אפס ב-6, מינימום מינוס 10 ב-9, אפס ב-12, מקסימום ב-15, מינימום ב-21 ואפס ב-24")
    X, Y = g.graph(60, 240, 440, 210, "t (s)", "v (cm/s)", xticks=[(v, str(v)) for v in range(3, 25, 3)], yticks=[(v, str(v)) for v in (-15, -10, -5, 5, 10, 15)], xmax=25.5, ymin=-16, ymax=16)
    g.curve(X, Y, lambda t: 10 * math.sin(w * t), 0, 25, n=160)
    return g

def yt_fig():
    g = Fig(460, 260, "גרף המקום כפונקציה של הזמן: מתחיל בנקודה הנמוכה, מינוס 0.19 מטר, עולה לשיא של 0.19 מטר אחרי שש שניות, וחוזר. שתי תנודות שלמות עד עשרים וארבע שניות")
    X, Y = g.graph(70, 130, 360, 100, "t (s)", "y (m)", xticks=[(v, str(v)) for v in (6, 12, 18, 24)], yticks=[(0.19, "0.19"), (-0.19, "−0.19")], xmax=26, ymin=-0.22, ymax=0.22)
    g.curve(X, Y, lambda t: -A * math.cos(math.pi * t / 6), 0, 24, n=120)
    return g

