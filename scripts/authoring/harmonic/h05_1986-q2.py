import math
m = 7.5; k = 30; w1 = math.sqrt(k / m)
t1 = math.pi / (2 * w1); vA = 0.1 * w1; u = vA / 2
w2 = math.sqrt(2 * k / (2 * m)); A2 = u / w2

def fig():
    g = Fig(560, 170, "משטח אופקי חלק בין שני קירות. קפיץ מהקיר השמאלי אל גוף A, גוף B צמוד אליו מימין, וקפיץ מ-B אל הקיר הימני. נקודת המגע בין הגופים מסומנת 0")
    gy = 130
    g.ground(60, 500, gy); g.wall(60, 50, gy); g.wall(500, 50, gy, side="right")
    g.spring(60, gy - 20, 230, gy - 20, coils=9)
    g.block(250, gy - 20, 40, 40, "A"); g.block(290, gy - 20, 40, 40, "B")
    g.spring(310, gy - 20, 500, gy - 20, coils=9)
    g.text(270, gy - 50, "0")
    return g

