        S(r"$A$ מתנודד לבד על הקפיץ שלו", r"מתנד קפיץ", r"\omega = \sqrt{\frac{k}{m}} = \sqrt{\frac{30}{7.5}} = 2\,\text{rad/s}"),
        S(r"מהקצה לשיווי המשקל", r"רבע מחזור", r"t = \frac{T}{4} = \frac{\pi}{2\omega} \approx 0.785\,\text{s}"),
