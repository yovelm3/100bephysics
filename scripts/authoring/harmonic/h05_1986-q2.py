        C(r"בדיקה באנרגיה", r"קינטית אחרי ההתנגשות שווה לאנרגיית שני הקפיצים בקצה", r"\frac{1}{2} \cdot 15 \cdot 0.1^2 = \frac{1}{2} \cdot 60 \cdot A'^2 \Rightarrow A' = 0.05\,\text{m}"),
