from mk import *
import math
m = 0.6; d = 0.15; k = m * 10 / d; T = 2 * math.pi * math.sqrt(m / k)
F = k * (d + 0.1); W = 0.5 * k * 0.1 ** 2

def fig():
    g = Fig(300, 210, "קפיץ תלוי מהתקרה, משקולת של 0.6 קילוגרם בקצהו. הנקודה O היא מצב שיווי המשקל, והנקודה M נמצאת 10 סנטימטר מתחתיה")
    cx = 130
    g.ceiling(70, 190, 25)
    g.spring(cx, 25, cx, 160, coils=10)
    g.block(cx, 172, 60, 24, "0.6 kg")
    g.line(60, 130, 230, 130, width=1, dash="4 4"); g.text(54, 134, "O", anchor="end")
    g.line(60, 172, 230, 172, width=1, dash="4 4"); g.text(54, 176, "M", anchor="end")
    g.line(210, 130, 210, 172, width=1.2, arrow=True, arrow_start=True); g.text(218, 156, "10 cm", cls="dim", anchor="start")
    return g

