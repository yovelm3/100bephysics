from mk import *
import math
m = 1.2; k = 30; w = math.sqrt(k / m); A = 0.1

def fig():
    g = Fig(520, 160, "קרונית על משטח אופקי, קשורה לקפיץ אופקי שקצהו השני מחובר לקיר. נקודת שיווי המשקל O, הנקודה A 10 סנטימטר מימין, והנקודה B משמאל")
    gy = 120
    g.ground(30, 490, gy); g.wall(50, 40, gy)
    g.spring(50, gy - 24, 300, gy - 24, coils=10)
    g.car(335, gy, w=80)
    for lab, x in (("B", 200), ("O", 270), ("A", 340)):
        g.line(x, gy + 2, x, gy + 12, width=1.4); g.text(x, gy + 28, lab)
    g.dim(270, 30, 340, 30, "10 cm", ext=False)
    return g

