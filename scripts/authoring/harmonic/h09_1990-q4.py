from mk import *
from lib import fbd
STRICT["on"] = True
import math
k = 50; m = 0.5; w = math.sqrt(k / m); A = 0.08; h = 2
v0 = A * w; t = (-v0 + math.sqrt(v0 ** 2 + 2 * 10 * h)) / 10

def fig():
    g = Fig(320, 250, "קפיץ תלוי מהתקרה ובקצהו משקולת. נקודת שיווי המשקל O בגובה 2 מטר מעל הרצפה, והנקודה A מעליה ב-0.08 מטר")
    cx = 140
    g.ceiling(80, 220, 25); g.ground(60, 260, 225)
    g.spring(cx, 25, cx, 92, coils=8)
    g.block(cx, 104, 30, 24)
    g.line(70, 92, 230, 92, width=1, dash="4 4"); g.text(64, 96, "A", anchor="end")
    g.line(70, 116, 230, 116, width=1, dash="4 4"); g.text(64, 120, "O", anchor="end")
    g.line(205, 92, 205, 116, width=1.2); g.text(214, 108, "0.08 m", cls="dim", anchor="start")
    g.line(205, 116, 205, 225, width=1.2, arrow=True, arrow_start=True); g.text(214, 175, "2 m", cls="dim", anchor="start")
    return g

