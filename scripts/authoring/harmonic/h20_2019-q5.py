from mk import *
import math
mA = 1; T0 = 1.0; k = 4 * math.pi ** 2 * mA / T0 ** 2
mB = lambda T: k * T * T / (4 * math.pi ** 2) - mA
POS = ["מעל נקודת שיווי המשקל", "בנקודת שיווי המשקל", "מתחת לנקודת שיווי המשקל"]

def fig():
    g = Fig(640, 480, "למעלה משמאל: גרף מסת הגוף mB בקילוגרם כפונקציה של זמן המחזור T בשניות: עקומה עולה מאפס ב-T שווה 1 עד כ-8.4 ב-T שווה 3.05. למעלה מימין: משטח A על קפיץ אנכי, וגוף B מונח עליו. למטה: ארבעה תרשימי כוחות על המסה m. בתרשים 1 כוח הקפיץ יחידה אחת כלפי מטה והכובד שתי יחידות כלפי מטה. בתרשים 2 כוח הקפיץ שתי יחידות כלפי מעלה והכובד שתיים כלפי מטה. בתרשים 3 כוח הקפיץ יחידה אחת כלפי מעלה והכובד שתיים כלפי מטה. בתרשים 4 כוח הקפיץ חמש יחידות כלפי מעלה והכובד שתיים כלפי מטה")
    X, Y = g.graph(50, 270, 300, 230, "T (s)", "mB (kg)", xticks=[(1, "1"), (2, "2"), (3, "3")], yticks=[(v, str(v)) for v in range(1, 10)], xmax=3.4, ymax=9.6)
    g.curve(X, Y, mB, 1.0, 3.05)
    cx = 510
    g.ground(410, 610, 260)
    g.spring(cx, 258, cx, 180, coils=7, amp=16, lead=4)
    g.rect(cx - 70, 168, 140, 12); g.text(cx + 78, 178, "A", anchor="start")
    g.block(cx, 140, 60, 56, "B")
    u = 18
    for i, (fs, lab) in enumerate([(-1, "1"), (2, "2"), (1, "3"), (5, "4")]):
        ox = 560 - i * 150; oy = 390
        g.rect(ox - 55, oy - 90, 110, 140, fill="none", stroke="var(--d-hatch)", width=1)
        g.dot(ox, oy); g.text(ox - 10, oy - 4, "m", anchor="end")
        g.line(ox, oy, ox, oy + 2 * u, width=1.6, arrow=True); g.text(ox + 6, oy + 2 * u + 4, "mg", anchor="start")
        if fs > 0:
            g.line(ox, oy, ox, oy - fs * u, width=1.6, arrow=True); g.text(ox + 6, oy - fs * u + 8, "Fsp", anchor="start")
        else:
            g.line(ox - 6, oy, ox - 6, oy - fs * u, width=1.6, arrow=True); g.text(ox - 12, oy + 22, "Fsp", anchor="end")
        g.text(ox, oy + 68, f"({lab})")
    return g

