from mk import *
import math
m = 1.2; v = 3; k = 30; w = math.sqrt(k / m)
t = math.pi / w; d = v / w

def fig():
    g = Fig(520, 160, "עגלה שמסתה m נעה ימינה במהירות v של 3 מטר לשנייה על משטח אופקי, לעבר קפיץ אופקי שקבועו k המחובר לקיר מימין")
    gy = 130
    g.ground(30, 490, gy); g.wall(490, 50, gy, side="right")
    g.car(140, gy, w=120, label="m")
    g.arrow(100, 50, 170, 50, "v = 3 m/s", lx=135, ly=40)
    g.spring(300, gy - 26, 490, gy - 26, coils=10, amp=10)
    g.text(400, gy - 50, "k = 30 N/m")
    return g

