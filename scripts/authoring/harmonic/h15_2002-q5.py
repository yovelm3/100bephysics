        S(r"בזמן המגע: חצי תנודה", r"מהעגלה נוגעת בקפיץ (שיווי משקל) עד שהיא חוזרת לאותה נקודה", r"t = \frac{T}{2} = \pi\sqrt{\frac{m}{k}}"),
