G3 = ["גרף I", "גרף II", "גרף III"]

def tri(t):
    u = (t + 1) % 4
    return 2 - abs(u - 2)
def bounce(t):
    u = t % 4
    return 20 - 5 * (u - 0) ** 2 if u <= 2 else 20 - 5 * (4 - u) ** 2

def fig():
    g = Fig(640, 445, "שלושה גרפים של מקום x כפונקציה של זמן t. גרף I: קשתות פרבוליות מ-20 מטר ב-t אפס, יורד לאפס ב-2 שניות, עולה ל-20 ב-4, וכן הלאה עד 10 שניות. גרף II: קוסינוס בין 0.1 למינוס 0.1 מטר, זמן מחזור 2 שניות. גרף III: קווים ישרים בין 0 ל-2 מטר: מתחיל ב-1, מגיע ל-2 ב-1 שנייה, ל-0 ב-3, ל-2 ב-5 וכן הלאה")
    X, Y = g.graph(370, 180, 220, 140, "t (s)", "x (m)", xticks=[(v, str(v)) for v in (2, 4, 6, 8, 10)], yticks=[(v, str(v)) for v in (5, 10, 15, 20)], xmax=10.5, ymax=22)
    g.curve(X, Y, bounce, 0, 10, n=200); g.heb(480, 222, "גרף I")
    X, Y = g.graph(50, 180, 220, 140, "t (s)", "x (m)", xticks=[(v, str(v)) for v in (1, 2, 3, 4, 5)], yticks=[(0.1, "0.1"), (0.05, "0.05"), (-0.05, "-0.05"), (-0.1, "-0.1")], xmax=5.3, ymin=-0.11, ymax=0.11)
    g.curve(X, Y, lambda t: 0.1 * math.cos(math.pi * t), 0, 5, n=160); g.heb(160, 222, "גרף II")
    X, Y = g.graph(210, 400, 220, 140, "t (s)", "x (m)", xticks=[(v, str(v)) for v in (2, 4, 6, 8, 10)], yticks=[(v, f"{v:g}") for v in (0.5, 1, 1.5, 2)], xmax=10.5, ymax=2.2)
    g.plot(X, Y, [(t / 10, tri(t / 10)) for t in range(0, 101)])
    g.heb(320, 432, "גרף III")
    return g

