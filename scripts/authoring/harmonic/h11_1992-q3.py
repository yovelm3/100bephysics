from mk import *
import math
N = [1, 2, 3, 4, 5, 6]; Tm = [0.63, 0.84, 1.01, 1.13, 1.26, 1.38]
n_ = len(N); T2 = [t * t for t in Tm]
mx = sum(N) / n_; my = sum(T2) / n_
slope = sum((a - mx) * (b - my) for a, b in zip(N, T2)) / sum((a - mx) ** 2 for a in N)
k = 4 * math.pi ** 2 * 0.3 / slope

def fig():
    g = Fig(560, 110, "טבלה: מספר הגלילים מ-1 עד 6, וזמן המחזור T בשניות: 0.63, 0.84, 1.01, 1.13, 1.26, 1.38")
    x0, y0, cw, hw = 20, 20, 62, 128
    W = cw * 6 + hw
    g.rect(x0, y0, W, 70, fill="none", width=1.2); g.line(x0, y0 + 35, x0 + W, y0 + 35, width=0.8)
    for i in range(1, 7): g.line(x0 + cw * i, y0, x0 + cw * i, y0 + 70, width=0.8)
    g.heb(x0 + cw * 6 + hw / 2, y0 + 23, "מספר הגלילים"); g.text(x0 + cw * 6 + hw / 2, y0 + 58, "T (s)")
    for i, (a, b) in enumerate(zip(reversed(N), reversed(Tm))):
        g.text(x0 + cw * (i + 0.5), y0 + 23, str(a)); g.text(x0 + cw * (i + 0.5), y0 + 58, f"{b:.2f}", cls="dim")
    return g

