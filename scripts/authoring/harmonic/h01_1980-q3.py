STRICT["on"] = True
import math
k = 20 / 0.1; m = 2; A = 0.1; w = math.sqrt(k / m)
vmax = A * w; tq = math.pi / (2 * w)

def fig():
    g = Fig(560, 186, "שולחן אופקי חלק. קפיץ שקצהו השמאלי מחובר לקיר, ולקצהו הימני מוצמדת מסה m של 2 קילוגרם. הקפיץ מתוח 10 סנטימטר משיווי משקל")
    gy = 120
    g.ground(40, 520, gy); g.wall(60, 40, gy)
    g.spring(60, gy - 22, 300, gy - 22, coils=10)
    g.block(325, gy - 22, 50, 44, "m")
    g.line(250, gy - 60, 250, gy + 2, width=1, dash="4 4"); g.heb(250, gy - 66, "שיווי משקל")
    g.dim(250, gy + 26, 300, gy + 26, "10 cm", ext=False, label_dy=6)
    return g

