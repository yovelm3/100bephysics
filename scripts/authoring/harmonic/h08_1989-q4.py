        S(r"שטח מתחת לגרף כוח-מקום", r"זו עבודת הכוח השקול", r"W = \frac{1}{2} \cdot 0.2 \cdot 8 = 0.8\,\text{J}"),
        S(r"משפט עבודה-אנרגיה", r"הכוח היחיד בכיוון התנועה", r"W = \Delta E_k"),
