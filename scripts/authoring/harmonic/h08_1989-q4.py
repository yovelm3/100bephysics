from mk import *
import math
m = 0.4; k = 8 / 0.2; w = math.sqrt(k / m); A = 0.2

def fig():
    g = Fig(520, 250, "גרף הכוח F בניוטון כפונקציה של ההעתק x במטרים: קו ישר יורד מ-8 ניוטון ב-x של מינוס 0.2 מטר, דרך הראשית, עד מינוס 8 ניוטון ב-x של 0.2 מטר")
    X = lambda v: 260 + v * 1000; Y = lambda v: 125 - v * 11
    for v in (-0.2, -0.1, 0.1, 0.2): g.line(X(v), Y(9), X(v), Y(-9), stroke="var(--d-hatch)", width=1)
    for v in (-8, 8): g.line(X(-0.22), Y(v), X(0.22), Y(v), stroke="var(--d-hatch)", width=1)
    g.line(X(-0.25), Y(0), X(0.25), Y(0), width=1.8, arrow=True); g.line(X(0), Y(-10), X(0), Y(10.5), width=1.8, arrow=True)
    g.text(X(0.25), Y(0) - 10, "x (m)", anchor="end"); g.text(X(0) + 10, Y(10.5) + 4, "F (N)", anchor="start")
    for v in (-0.2, -0.1, 0.1, 0.2): g.text(X(v), Y(0) + 18, f"{v:g}", cls="dim")
    for v in (-8, 8): g.text(X(0) - 8, Y(v) + 4, str(v), cls="dim", anchor="end")
    g.plot(X, Y, [(-0.2, 8), (0.2, -8)])
    return g

