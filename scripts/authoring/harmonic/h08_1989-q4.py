        S(r"צורת הגרף", r"קו ישר דרך הראשית בשיפוע שלילי: הכוח פרופורציוני להעתק ובכיוון הפוך", r"F = -kx,\quad k = \frac{8}{0.2} = 40\,\text{N/m}"),
