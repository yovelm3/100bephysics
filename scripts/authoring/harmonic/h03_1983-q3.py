from mk import *

def fig():
    g = Fig(300, 320, "קפיץ תלוי מהתקרה. בקצהו התחתון גוף A שמסתו 2m, ומתחתיו גוף B שמסתו m תלוי בחוט")
    cx = 150
    g.ceiling(90, 210, 30)
    g.spring(cx, 30, cx, 170, coils=10)
    g.block(cx, 192, 50, 40, "A"); g.text(cx + 40, 197, "2m", anchor="start")
    g.line(cx, 212, cx, 250, width=1.6)
    g.block(cx, 270, 44, 36, "B"); g.text(cx + 38, 275, "m", anchor="start")
    return g

E(id="bagrut-1983-q3", year=1983, label="1983 שאלה 3", topic="harmonic", sub="harm-spring", diff=3, fig=fig,
  stem=r"קפיץ מחובר אל התקרה ועליו תלוי גוף $A$ שמסתו $2m$. אל גוף $A$ מחובר בחוט (שמסתו זניחה) גוף $B$ שמסתו $m$. כשהמערכת במנוחה, התארכותו של הקפיץ (התוספת לאורכו של הקפיץ החופשי) היא $d$. ברגע מסוים ניתק החוט, והגוף $B$ נופל. בטא את תשובותיך בעזרת הגדלים $m$, $d$ ו-$g$ (תאוצת הנפילה החופשית).",
  parts=[
    P("א", r"מהי משרעת (אמפליטודה) התנודות של הגוף $A$?", OPEN, ["fbd", "algebra"], [
        S(r"קבוע הקפיץ", r"לפני הניתוק הקפיץ מחזיק את שני הגופים", r"kd = 3mg \Rightarrow k = \frac{3mg}{d}"),
        S(r"שיווי המשקל החדש", r"אחרי הניתוק נשאר רק $A$", r"kx_0 = 2mg \Rightarrow x_0 = \frac{2d}{3}"),
        S(r"משרעת", r"$A$ מתחיל במנוחה, ולכן זו נקודת קצה", r"A = d - \frac{2d}{3} = \frac{d}{3}"),
    ], r"$\frac{d}{3}$", key=r"d/3"),
    P("ב", r"מהו זמן המחזור של התנודות?", OPEN, ["principle", "algebra"], [
        S(r"מתנד קפיץ", r"המסה המתנודדת $2m$", r"T = 2\pi\sqrt{\frac{2m}{k}} = 2\pi\sqrt{\frac{2m d}{3mg}} = 2\pi\sqrt{\frac{2d}{3g}}"),
    ], r"$T = 2\pi\sqrt{\frac{2d}{3g}}$", key=r"2π√(2d/3g)"),
    P("ג", r"מהי המהירות המרבית של הגוף $A$ בעת תנודותיו?", OPEN, ["principle", "algebra"], [
        S(r"מהירות מרבית", r"בשיווי המשקל", r"v_{\max} = A\omega = \frac{d}{3}\sqrt{\frac{3g}{2d}} = \sqrt{\frac{dg}{6}}"),
    ], r"$\sqrt{\frac{dg}{6}}$", key=r"√(dg/6)"),
    P("ד", r"מהו הכוח השקול המרבי הפועל על הגוף $A$?", OPEN, ["fbd", "algebra"], [
        S(r"כוח שקול מרבי", r"בנקודת הקצה, העתק מרבי משיווי המשקל", r"F_{\max} = kA = \frac{3mg}{d} \cdot \frac{d}{3} = mg"),
        C(r"בדיקה ברגע הניתוק", r"הקפיץ עדיין דוחף $3mg$, והכובד על $A$ הוא $2mg$", r"F = 3mg - 2mg = mg"),
    ], r"$mg$", key=r"mg"),
  ],
  concepts=["מתנד קפיץ אנכי", "שיווי משקל חדש", "משרעת", "כוח שקול מרבי"],
  summary=r"מנתקים גוף תחתון ממערכת על קפיץ: שיווי משקל חדש, משרעת $d/3$, זמן מחזור ומהירות מרבית.")
