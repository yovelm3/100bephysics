from mk import *
import math
M = 0.8; T = 1.2; A = 15
k = 4 * math.pi ** 2 * M / T ** 2
y = lambda t: -A * math.cos(2 * math.pi * t / T)

def fig():
    g = Fig(560, 230, "גרף מקום המשקולת y בסנטימטרים כפונקציה של הזמן t בשניות: מתחיל ב-מינוס 15, חוצה את האפס ב-0.3, מגיע ל-15 ב-0.6, אפס ב-0.9, מינוס 15 ב-1.2, אפס ב-1.5, 15 ב-1.8 ואפס ב-2.1")
    X, Y = g.graph(60, 210, 440, 180, "t (s)", "y (cm)", xticks=[(v, f"{v:g}") for v in (0.3, 0.6, 0.9, 1.2, 1.5, 1.8, 2.1)], yticks=[(15, "15"), (-15, "-15")], xmax=2.4, ymin=-18, ymax=18)
    g.curve(X, Y, y, 0, 2.25, n=120)
    return g

