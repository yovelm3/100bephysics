def fig():
    g = Fig(640, 250, "למעלה: עגלה M צמודה לקפיץ מכווץ המחובר לקיר משמאל, וסרגל x בסנטימטרים מ-0 עד 40. העגלה מתחילה בנקודה B1 ב-x אפס, הנקודה C ב-36.1 והנקודה B2 ב-40. למטה: טבלה של זמן ומקום כל 0.1 שנייה מ-0 עד 1 שנייה")
    gy = 70
    g.wall(40, 20, gy); g.spring(40, gy - 12, 92, gy - 12, coils=6, amp=8, lead=4); g.block(110, gy - 12, 36, 24, "M")
    g.line(30, gy, 600, gy, width=1.4)
    X = lambda v: 110 + v * 10.5
    g.line(X(-1), gy + 30, X(44), gy + 30, width=1.4, arrow=True); g.text(X(44) + 16, gy + 50, "x (cm)", anchor="end")
    for v in range(0, 45, 5):
        g.line(X(v), gy + 26, X(v), gy + 34, width=1.2); g.text(X(v), gy + 50, str(v), cls="dim")
    for lab, v in (("B₁", 0), ("C", 36.1), ("B₂", 40)):
        g.text(X(v), gy + 18, lab)
    x0, y0, hw, cw = 20, 150, 70, 50
    W = hw + cw * 11
    g.rect(x0, y0, W, 72, fill="none", width=1.2)
    for r in (24, 48): g.line(x0, y0 + r, x0 + W, y0 + r, width=0.8)
    for i in range(12): g.line(x0 + W - hw - cw * i, y0, x0 + W - hw - cw * i, y0 + 72, width=0.8)
    g.heb(x0 + W - hw / 2, y0 + 17, "הנקודה"); g.text(x0 + W - hw / 2, y0 + 41, "t (s)"); g.text(x0 + W - hw / 2, y0 + 65, "x (cm)")
    names = {0: "B₁", 8: "C", 10: "B₂"}
    for i, (t, x) in enumerate(zip(ts, xs)):
        cx = x0 + W - hw - cw * (i + 0.5)
        if i in names: g.text(cx, y0 + 17, names[i])
        g.text(cx, y0 + 41, f"{t:.1f}", cls="dim"); g.text(cx, y0 + 65, f"{x:.1f}", cls="dim")
    return g

