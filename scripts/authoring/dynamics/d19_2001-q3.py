from mk import *
T = [0, 0.02, 0.04, 0.06, 0.08, 0.1]; V = [0, 0.038, 0.083, 0.123, 0.158, 0.200]
n = len(T); tm = sum(T) / n; vm = sum(V) / n
slope = sum((t - tm) * (v - vm) for t, v in zip(T, V)) / sum((t - tm) ** 2 for t in T)

def fig():
    g = Fig(560, 240, "גוף A (שתי תיבות מודבקות) על שולחן, קשור בחוט שעובר על גלגלת לגוף B (תיבה אחת) שתלוי. וטבלת המהירות של A כל 0.02 שניות")
    g.rect(60, 90, 300, 10, fill="url(#f-hatch)", stroke="none", width=0); g.line(60, 90, 360, 90); g.line(360, 90, 360, 140)
    g.block(160, 76, 40, 26, None, fill="var(--d-fill)", text_color="var(--d-label)"); g.block(160, 50, 40, 26, None, fill="var(--d-fill)")
    g.text(160, 30, "A")
    g.pulley(372, 78, 12); g.line(180, 76, 372, 66, width=1.5); g.line(384, 78, 384, 120, width=1.5)
    g.block(384, 133, 40, 26, None, fill="var(--d-fill)"); g.text(412, 140, "B", anchor="start")
    x0, y0 = 40, 175
    g.rect(x0, y0, 480, 52, fill="none", width=1.5); g.line(x0, y0 + 26, x0 + 480, y0 + 26, width=1.2); g.line(x0 + 90, y0, x0 + 90, y0 + 52, width=1.2)
    g.text(x0 + 45, y0 + 18, "t (s)"); g.text(x0 + 45, y0 + 44, "v (m/s)")
    for i, (t, v) in enumerate(zip(T, V)):
        cx = x0 + 90 + 32 + i * 64
        g.text(cx, y0 + 18, f"{t:g}", cls="dim"); g.text(cx, y0 + 44, f"{v:.3f}", cls="dim")
    return g

