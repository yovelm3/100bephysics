def acrobat(g, x, y, s=1.0):
    g.circle(x, y, 7 * s, fill="var(--d-label)")
    g.line(x, y + 7 * s, x, y + 50 * s, width=4 * s); g.line(x, y + 50 * s, x - 6 * s, y + 80 * s, width=3 * s); g.line(x, y + 50 * s, x + 6 * s, y + 80 * s, width=3 * s)
    g.line(x, y + 14 * s, x - 7 * s, y - 10 * s, width=2.5 * s); g.line(x, y + 14 * s, x + 7 * s, y - 10 * s, width=2.5 * s)

