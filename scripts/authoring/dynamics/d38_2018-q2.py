import math
F = [20, 30, 40, 50, 60]; A_ = [3.0, 5.0, 7.4, 9.1, 12.5]
n = 5; fm = sum(F) / n; am = sum(A_) / n
slope = sum((f - fm) * (a - am) for f, a in zip(F, A_)) / sum((f - fm) ** 2 for f in F)
icpt = am - slope * fm
m = 1 / (2 * slope); F0 = -icpt / slope

