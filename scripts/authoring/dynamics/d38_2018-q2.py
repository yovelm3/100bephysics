def agraph():
    g = Fig(560, 300, "גרף התשובה: התאוצה כפונקציה של הכוח. חמש נקודות מהטבלה על קו ישר, שחותך את ציר הכוח בערך ב-8 ניוטון")
    X, Y = g.graph(70, 260, 420, 220, "F (N)", "a (m/s²)", xticks=[(f, str(f)) for f in (8, 20, 30, 40, 50, 60)], yticks=[(v, str(v)) for v in (2, 4, 6, 8, 10, 12)], xmax=64, ymax=13.5)
    g.plot(X, Y, [(F0, 0), (62, slope * 62 + icpt)])
