def fig():
    g = Fig(560, 300, "לוח משופע חלק ABCD בזווית 30 מעלות. גלגלת P בצלע העליונה BC. חוט שעובר על הגלגלת קשור לגוף M1 במסה 3 קילוגרם ולגוף M2 במסה 2 קילוגרם, ושניהם על הלוח")
    A = (60, 270); u = (70, 0); w = (40, -56)
    Pt = lambda a, b: (A[0] + a * u[0] + b * w[0], A[1] + a * u[1] + b * w[1])
    D, C, B = Pt(4.5, 0), Pt(4.5, 3.5), Pt(0, 3.5)
    g.poly([A, D, C, B])
    Cf = (C[0], D[1])
    g.poly([D, Cf, C], fill="none", width=1.5, dash="5 4")
    g.angle(D[0], D[1], 36, 0, 54.5, "α", lr=50)
    for p, t, dx, dy in [(A, "A", -12, 16), (D, "D", 0, 20), (C, "C", 10, -6), (B, "B", -12, -6)]:
        g.text(p[0] + dx, p[1] + dy, t)
    Pp = Pt(2.25, 3.5)
    g.pulley(Pp[0], Pp[1] - 6, 10); g.text(Pp[0], Pp[1] - 24, "P")
    m2 = Pt(1.85, 1.6); m1 = Pt(2.65, 1.6)
    g.line(Pp[0] - 10, Pp[1] - 6, m2[0], m2[1] - 6, width=1.5); g.line(Pp[0] + 10, Pp[1] - 6, m1[0], m1[1] - 6, width=1.5)
    g.block(m2[0], m2[1] + 6, 26, 18, None, angle=-8); g.text(m2[0] - 26, m2[1] + 12, "M₂", anchor="end")
    g.block(m1[0], m1[1] + 6, 30, 20, None, angle=-8); g.text(m1[0] + 26, m1[1] + 12, "M₁", anchor="start")
    return g

def slope_fbd(label, up_T, note, pos, extra_alt):
    forces = [(f"{label}g", -90, 1.1), ("N", 90 + 30, 0.95)] + ([("T", 30, 0.75)] if up_T is not None else [])
    return lambda: fbd(forces, f"תרשים כוחות על הגוף {label} במבט מהצד: כוח הכובד כלפי מטה, הכוח הנורמלי ניצב ללוח" + extra_alt,
                       positive=pos, body="block", body_label=label, tilt=30, surface="below", note=note)

