STRICT["on"] = True
F = [3, 3.5, 4, 4.5, 5, 5.5]; A_ = [1.5, 2.5, 3.5, 4, 5, 6]
n = 6; Fm = sum(F) / n; am = sum(A_) / n
slope = sum((f - Fm) * (a - am) for f, a in zip(F, A_)) / sum((f - Fm) ** 2 for f in F)
F0 = Fm - am / slope; mB = F0 / 10; a6 = slope * (6 - F0); T6 = mB * (10 + a6)

