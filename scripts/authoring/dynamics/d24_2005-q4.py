from mk import *
F = [3, 3.5, 4, 4.5, 5, 5.5]; A_ = [1.5, 2.5, 3.5, 4, 5, 6]
n = 6; Fm = sum(F) / n; am = sum(A_) / n
slope = sum((f - Fm) * (a - am) for f, a in zip(F, A_)) / sum((f - Fm) ** 2 for f in F)
F0 = Fm - am / slope; mB = F0 / 10; a6 = slope * (6 - F0); T6 = mB * (10 + a6)

def fig():
    g = Fig(560, 230, "גוף A על משטח חלק, מחובר בחוט שעובר על גלגלת לגוף B שתלוי. התלמיד מושך את A ימינה בכוח F דרך מד-כוח. וטבלת התאוצה כפונקציה של הכוח")
    g.rect(60, 90, 220, 10, fill="url(#f-hatch)", stroke="none", width=0); g.line(60, 90, 280, 90); g.line(60, 90, 60, 200)
    g.block(130, 72, 40, 34, "A"); g.pulley(48, 78, 12); g.line(48, 66, 110, 66, width=1.5); g.line(36, 78, 36, 140, width=1.5)
    g.block(36, 156, 28, 30, "B")
    g.line(150, 72, 180, 72, width=1.5); g.spring(180, 72, 220, 72, coils=5, amp=5, lead=4); g.rect(176, 60, 48, 24, fill="none", width=1.2)
    g.arrow(224, 72, 270, 72, "F", lx=278, ly=76, anchor="start"); g.heb(200, 52, "מד-כוח")
    x0, y0 = 300, 90
    g.rect(x0, y0, 250, 52, fill="none", width=1.5); g.line(x0, y0 + 26, x0 + 250, y0 + 26, width=1.2); g.line(x0 + 64, y0, x0 + 64, y0 + 52, width=1.2)
    g.text(x0 + 32, y0 + 18, "F (N)"); g.text(x0 + 32, y0 + 44, "a (m/s²)")
