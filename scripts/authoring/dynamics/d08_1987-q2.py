def fig():
    g = Fig(560, 230, "גרף התאוצה a כפונקציה של הכוח F: קו ישר שחותך את ציר הכוח ב-2 ניוטון ומגיע ל-2 מטר לשנייה בריבוע ב-10 ניוטון")
    X, Y = g.graph(120, 200, 340, 150, "F (N)", "a (m/s²)", xticks=[(f, str(f)) for f in (2, 4, 6, 8, 10)], yticks=[(1, "1"), (2, "2")], xmax=11, ymax=2.6)
    g.plot(X, Y, [(2, 0), (10.4, 2.1)])
    return g

