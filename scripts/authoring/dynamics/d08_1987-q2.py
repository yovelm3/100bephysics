def agraph():
    g = Fig(560, 280, "גרף התשובה: התאוצה כפונקציה של הכוח. הקו המקורי חותך את ציר הכוח ב-2 ניוטון ומגיע ל-2 מטר לשנייה בריבוע ב-10 ניוטון. הקו החדש חותך את ציר הכוח ב-4 ניוטון, ומגיע ל-1 ב-12 ניוטון")
    X, Y = g.graph(70, 240, 420, 190, "F (N)", "a (m/s²)", xticks=[(f, str(f)) for f in (2, 4, 6, 8, 10, 12)], yticks=[(1, "1"), (2, "2")], xmax=13, ymax=2.5)
    g.plot(X, Y, [(2, 0), (10.4, 2.1)], stroke="var(--d-label)", dash="6 4")
    g.plot(X, Y, [(4, 0), (12.8, 1.1)])
    g.heb(X(9.2), Y(2.1), "הגוף המקורי", anchor="end")
    g.heb(X(12.8), Y(1.1) - 12, "הגוף החדש", anchor="end")
    return g

