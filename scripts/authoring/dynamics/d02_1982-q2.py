def cart_fbd(with_F, note):
    forces = ([("F", 180, 1.5)] if with_F else []) + [("T", 0, 1.0), ("N", 90, 1.1), ("mg", -90, 1.1)]
    return lambda: fbd(forces, "תרשים כוחות על הקרונית: " + ("הכוח F שמאלה, " if with_F else "") + "מתיחות החוט T ימינה, הכוח הנורמלי N כלפי מעלה וכוח הכובד mg כלפי מטה. הכיוון החיובי שמאלה",
                       positive=180, body="block", body_label="m", surface="below", note=note)

def weight_fbd():
    return lambda: fbd([("T", 90, 1.0), ("Mg", -90, 1.0)], "תרשים כוחות על המשקולת: מתיחות החוט T כלפי מעלה וכוח הכובד Mg כלפי מטה. הכיוון החיובי כלפי מעלה, כי כשהקרונית נעה שמאלה המשקולת עולה",
                       positive=90, body="block", body_label="M", note="אותה מתיחות")

