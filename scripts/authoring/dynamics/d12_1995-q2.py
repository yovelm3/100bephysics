def fig():
    g = Fig(560, 270, "תרשים א: גוף M וגוף m קשורים בחוט על משטח אופקי, וכוח F מושך את m ימינה. תרשים ב: במקום הכוח, חוט מעל גלגלת עם משקולת שמשקלה F")
    for y0, lab, pul in ((100, "תרשים א", False), (230, "תרשים ב", True)):
        g.rect(40, y0, 360, 10, fill="url(#f-hatch)", stroke="none", width=0); g.line(40, y0, 400, y0)
        g.block(140, y0 - 25, 90, 50, "M"); g.block(290, y0 - 22, 60, 44, "m")
        g.line(185, y0 - 25, 260, y0 - 22, width=1.5)
        if pul:
            g.line(400, y0, 400, y0 + 30); g.pulley(412, y0 - 10, 12)
            g.line(320, y0 - 22, 412, y0 - 22, width=1.5); g.line(424, y0 - 10, 424, y0 + 10, width=1.5)
            g.block(424, y0 + 26, 28, 28, None, fill="var(--d-fill)")
        else:
            g.arrow(320, y0 - 22, 380, y0 - 22, "F", lx=390, ly=y0 - 18, anchor="start")
        g.heb(470, y0 - 20, lab)
    return g

