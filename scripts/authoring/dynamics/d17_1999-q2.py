def fig():
    g = Fig(560, 300, "שני גופים, A במסה 3 קילוגרם ו-B במסה 2 קילוגרם, תלויים משני צדי גלגלת. אדם מחזיק את B. שניהם בגובה 3.5 מטר מעל הרצפה")
    g.ceiling(200, 360, 20); g.line(280, 20, 280, 50, width=1.5)
    g.pulley(280, 80, 32)
    g.line(248, 80, 248, 190, width=1.5); g.line(312, 80, 312, 190, width=1.5)
    g.block(248, 205, 34, 30, "B"); g.block(312, 205, 34, 30, "A")
    g.text(248, 240, "2 kg", cls="dim"); g.text(312, 240, "3 kg", cls="dim")
    g.path("M 160,210 Q 200,200 230,206", width=3); g.heb(150, 196, "יד")
    g.ground(80, 480, 290)
    g.line(180, 220, 230, 220, stroke="var(--d-dim)", width=1, dash="3 3")
    g.dim(200, 220, 200, 290, "3.5 m")
    return g

def hang(forces, lab, alt, note, pos):
    return lambda: fbd(forces, alt, positive=pos, body="block", body_label=lab, note=note)

