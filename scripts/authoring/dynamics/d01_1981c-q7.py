def cart(g, x, y, pend, ball, label=None, w=96, h=70):
    g.rect(x, y, w, h, fill="var(--d-fill)")
    for wx in (x + 22, x + w - 22):
        g.circle(wx, y + h + 9, 9, fill="none", stroke="var(--d-line)")
    px = x + w / 2 + (pend * 30)
    g.line(x + w / 2, y, px, y + 20, width=1.5); g.circle(px, y + 20, 6, fill="var(--d-label)")
    bx = x + w / 2 + (ball * 30)
    g.line(x + w / 2, y + h, bx, y + h - 18, width=1.5); g.circle(bx, y + h - 24, 6, fill="#ffffff", stroke="var(--d-line)")
    if label:
        g.heb(x + w / 2, y + h + 38, label)

def fig():
    g = Fig(560, 270, "קרון סגור: מטוטלת תלויה מהתקרה וכדור הליום קשור ברצפה. למעלה: מצב שיווי המשקל במנוחה. למטה: ארבע אפשרויות א עד ד כשהקרון מאיץ ימינה")
    cart(g, 232, 10, 0, 0)
    g.arrow(350, 40, 400, 40, "a", lx=375, ly=32)
    opts = [("א", 0.7, -0.7), ("ב", -0.7, 0.7), ("ג", 0.7, 0.7), ("ד", -0.7, -0.7)]
    for i, (lab, p, b) in enumerate(reversed(opts)):
        cart(g, 20 + i * 135, 130, p, b, lab)
    return g

