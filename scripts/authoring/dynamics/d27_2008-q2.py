def fig():
    g = Fig(560, 230, "גרף מהירות-זמן של מעלית: עולה מאפס ל-1 מטר לשנייה ב-2 שניות, קבועה עד 8, ויורדת לאפס ב-12 שניות")
    X, Y = g.graph(100, 200, 360, 150, "t (s)", "v (m/s)", xticks=[(t, str(t)) for t in range(1, 13)], yticks=[(0.5, "0.5"), (1, "1")], xmax=13, ymax=1.2)
    g.plot(X, Y, [(0, 0), (2, 1), (8, 1), (12, 0)])
    for t in (2, 8): g.line(X(t), Y(1), X(t), Y(0), stroke="var(--d-dim)", width=1, dash="4 3")
    return g

