    for x in (90, 470):
        g.line(x, 30, x, 64, width=1.5); g.pulley(x, 78, 16)
    g.line(90, 62, 190, 62, width=1.5); g.spring(190, 62, 370, 62, coils=10); g.line(370, 62, 470, 62, width=1.5)
    for x, sx in ((74, 74), (486, 486)):
        g.line(sx, 78, sx, 170, width=1.5); g.block(sx, 190, 40, 40, "16 kg")
    return g

