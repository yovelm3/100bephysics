from mk import *

def fig():
    g = Fig(560, 280, "תרשים 1: גוף של 200 גרם תלוי על שני קפיצים זהים זה לצד זה. תרשים 2: אותו גוף תלוי על שני הקפיצים זה מתחת לזה")
    g.ceiling(320, 480, 30); g.ceiling(80, 240, 30)
    g.spring(380, 30, 380, 120, coils=9); g.spring(420, 30, 420, 120, coils=9)
    g.block(400, 136, 80, 30, "200 g", fill="var(--d-fill)", text_color="var(--d-label)")
    g.spring(160, 30, 160, 120, coils=9); g.spring(160, 120, 160, 210, coils=9)
    g.block(160, 226, 80, 30, "200 g", fill="var(--d-fill)", text_color="var(--d-label)")
    g.heb(400, 270, "תרשים 1"); g.heb(160, 270, "תרשים 2")
    return g

