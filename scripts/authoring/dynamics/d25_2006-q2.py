from mk import *
import math

def fig():
    g = Fig(560, 200, "מכונית על כביש אופקי. משקולת תלויה בחוט מהתקרה, והחוט נוטה בזווית קבועה של 30 מעלות מהאנך, כשהמשקולת מאחור")
