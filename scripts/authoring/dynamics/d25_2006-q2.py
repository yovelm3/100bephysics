    g.line(300, 40, 300 - L * math.sin(a), 40 + L * math.cos(a), width=1.5); g.circle(300 - L * math.sin(a), 40 + L * math.cos(a), 8, fill="var(--d-label)")
    g.line(300, 40, 300, 130, stroke="var(--d-dim)", width=1, dash="3 3")
    g.angle(300, 40, 30, 240, 270, "α", lr=44)
    return g

