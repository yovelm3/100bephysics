    g.pulley(144, 26, 10); g.line(138, 34, 138, 70, width=1.5); g.block(138, 84, 22, 26, "m₂")
    g.block(300, 92, 34, 22, "m₁", angle=-26.6); g.line(150, 18, 286, 86, width=1.5)
