def fig():
    g = Fig(560, 260, "תרשים א: מכונית על כביש אופקי, ומשקולת תלויה ממד-כוח בתקרה, החוט נוטה בזווית אלפא מהאנך. תרשים ב: המכונית עולה בכביש משופע במהירות קבועה, והחוט אנכי")
    g.ground(20, 260, 200)
    g.rect(50, 70, 180, 110, fill="none"); g.circle(85, 192, 9, fill="var(--d-label)"); g.circle(195, 192, 9, fill="var(--d-label)")
    g.line(140, 70, 108, 140, width=1.5); g.rect(120, 86, 10, 24, fill="var(--d-fill)"); g.circle(106, 146, 8, fill="var(--d-label)")
    g.line(140, 70, 140, 140, stroke="var(--d-dim)", width=1, dash="3 3"); g.text(130, 132, "α", anchor="end")
    g.heb(140, 236, "תרשים א")
    a = math.radians(20)
    g.path("M 300,240 L 540,152", width=2)
    cx, cy = 420, 140
    def R(x, y):
        return (cx + x * math.cos(a) + y * math.sin(a), cy - x * math.sin(a) + y * math.cos(a))
    g.poly([R(-80, -55), R(80, -55), R(80, 45), R(-80, 45)], fill="none")
    top = R(0, -55)
    g.line(top[0], top[1], top[0], top[1] + 80, width=1.5); g.circle(top[0], top[1] + 86, 8, fill="var(--d-label)")
    n = R(0, 25); g.line(top[0], top[1], n[0], n[1], stroke="var(--d-dim)", width=1, dash="3 3"); g.text(top[0] + 10, top[1] + 60, "α", anchor="start")
    g.heb(420, 254, "תרשים ב")
    return g

