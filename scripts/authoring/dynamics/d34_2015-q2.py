import math
MU = [0.10, 0.15, 0.20, 0.25, 0.30]; A_ = [2.5, 2.0, 1.6, 1.1, 0.6]
n = 5; mm = sum(MU) / n; am = sum(A_) / n
slope = sum((u - mm) * (a - am) for u, a in zip(MU, A_)) / sum((u - mm) ** 2 for u in MU)
alpha = math.degrees(math.acos(-slope / 10))

def fig():
    g = Fig(560, 230, "גוף על מדרון בזווית אלפא, וטבלת המדידות: מקדם החיכוך מ-0.10 עד 0.30 והתאוצה מ-2.5 עד 0.6 מטר לשנייה בריבוע")
    g.poly([(60, 120), (300, 120), (60, 40)], fill="var(--d-fill)")
    g.angle(300, 120, 40, 180 - 18.4, 180, "α", lr=54)
    g.block(130, 80, 34, 24, None, angle=-18.4)
    x0, y0 = 60, 150
    g.rect(x0, y0, 440, 52, fill="none", width=1.5); g.line(x0, y0 + 26, x0 + 440, y0 + 26, width=1.2); g.line(x0 + 90, y0, x0 + 90, y0 + 52, width=1.2)
    g.text(x0 + 45, y0 + 18, "μ"); g.text(x0 + 45, y0 + 44, "a (m/s²)")
    for i, (u, a) in enumerate(zip(MU, A_)):
        cx = x0 + 90 + 35 + i * 70
        g.text(cx, y0 + 18, f"{u:.2f}", cls="dim"); g.text(cx, y0 + 44, f"{a:g}", cls="dim")
    return g

b0 = am - slope * mm

def agraph():
    g = Fig(560, 300, "גרף התשובה: התאוצה כפונקציה של מקדם החיכוך. חמש נקודות מהטבלה על קו ישר יורד, שחותך את ציר התאוצה בערך ב-3.44 ואת ציר מקדם החיכוך בערך ב-0.37")
    X, Y = g.graph(70, 260, 420, 220, "μ", "a (m/s²)", xticks=[(u, f"{u:g}") for u in (0.1, 0.2, 0.3, 0.4)], yticks=[(v, str(v)) for v in (1, 2, 3)], xmax=0.42, ymax=3.8)
    g.plot(X, Y, [(0, b0), (-b0 / slope, 0)])
    for u, a in zip(MU, A_):
        g.circle(X(u), Y(a), 5, fill="var(--d-label)")
    g.circle(X(0), Y(b0), 4.5, fill="var(--d-ask)"); g.circle(X(-b0 / slope), Y(0), 4.5, fill="var(--d-ask)")
    g.text(X(0) + 10, Y(b0) - 6, "3.44", cls="dim", anchor="start")
    return g

