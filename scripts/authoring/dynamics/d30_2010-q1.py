    g.rect(x0, y0, 500, 72, fill="none", width=1.5)
    for r in (24, 48): g.line(x0, y0 + r, x0 + 500, y0 + r, width=1.2)
    g.line(x0 + 110, y0, x0 + 110, y0 + 72, width=1.2)
