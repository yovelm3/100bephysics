    for i, (n, a) in enumerate(zip(N, A_)):
        cx = x0 + 110 + 32 + i * 65
        g.text(cx, y0 + 17, str(n), cls="dim"); g.text(cx, y0 + 41, f"{a:.2f}", cls="dim"); g.text(cx, y0 + 65, str(6 - n), cls="dim")
    return g

