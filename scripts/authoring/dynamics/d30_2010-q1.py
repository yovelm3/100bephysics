STRICT["on"] = True
N = [0, 1, 2, 3, 4, 5]; A_ = [0.43, 1.66, 2.91, 4.16, 5.40, 6.67]
Fg = [(0.1 + 0.3 * n) * 10 for n in N]
m = len(N); fm = sum(Fg) / m; am = sum(A_) / m
slope = sum((f - fm) * (a - am) for f, a in zip(Fg, A_)) / sum((f - fm) ** 2 for f in Fg)
M0 = 1 / slope - 0.1 - 1.8

