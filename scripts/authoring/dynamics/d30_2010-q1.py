    g.rect(90, 58, 120, 34, fill="var(--d-fill)"); g.text(150, 82, "M₀")
    for i in range(6): g.rect(96 + i * 19, 40, 14, 18, fill="var(--d-body)")
    for x in (110, 190): g.circle(x, 94, 6, fill="var(--d-label)")
    g.pulley(352, 88, 12); g.line(210, 76, 352, 76, width=1.5); g.line(364, 88, 364, 140, width=1.5)
