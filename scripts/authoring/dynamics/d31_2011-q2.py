def fig():
    g = Fig(560, 330, "תרשים א: קופסה M על שולחן אופקי, נמשכת בקפיץ, ולידה גלילים במסה m. תרשים ב: התארכות הקפיץ כפונקציה של מספר הגלילים בקופסה, נקודות על קו ישר מ-0.07 מטר בגליל אחד עד 0.17 בשישה")
