    g.block(140, 50, 70, 40, "M", fill="var(--d-fill)", text_color="var(--d-label)")
    g.spring(175, 50, 260, 50, coils=7); g.arrow(260, 50, 320, 50, "F", lx=330, ly=54, anchor="start")
    for i in range(4): g.circle(60 + i * 14, 62, 6, fill="none", stroke="var(--d-line)")
    g.text(60, 46, "m", cls="dim")
    g.heb(470, 60, "תרשים א")
    X, Y = g.graph(80, 310, 340, 190, "n", "Δℓ (m)", xticks=[(n, str(n)) for n in range(1, 8)], yticks=[(v / 100, f"{v/100:g}") for v in range(2, 21, 2)], xmax=7, ymax=0.2)
    for n, d in NP: g.dot(X(n), Y(d))
    g.plot(X, Y, [(0.5, 0.06), (6.5, 0.18)], width=1.6)
    g.heb(470, 220, "תרשים ב")
    return g

