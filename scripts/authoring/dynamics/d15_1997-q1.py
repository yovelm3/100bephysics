def fig():
    g = Fig(560, 240, "גוף על מדרון חלק בזווית 30 מעלות. מהירותו 12 מטר לשנייה במורד המדרון, וכוח F של 3.6 ניוטון פועל עליו במעלה המדרון. ציר x במורד המדרון")
    g.poly([(60, 210), (480, 210), (60, 50)], fill="var(--d-fill)")
    g.ground(40, 500, 210)
    g.angle(480, 210, 50, 180 - 20.85, 180, "30°", lr=70)
    cx, cy = 230, 125
    g.block(cx, cy - 16, 44, 26, None, angle=-20.85)
    g.arrow(cx + 26, cy - 22, cx + 80, cy - 1, "12 m/s", lx=cx + 92, ly=cy - 2, anchor="start")
    g.arrow(cx - 24, cy - 30, cx - 80, cy - 52, "F = 3.6 N", lx=cx - 84, ly=cy - 58, anchor="end")
    g.dot(cx, cy + 6, 3); g.text(cx - 2, cy + 26, "0")
    g.arrow(cx + 40, cy + 30, cx + 100, cy + 53, "x", lx=cx + 108, ly=cy + 60, anchor="start")
    return g

def vgraph():
    g = Fig(560, 300, "גרף התשובה: מהירות הגוף כפונקציה של הזמן. קו ישר יורד מ-12 מטר לשנייה ברגע אפס, חוצה את האפס אחרי 3 שניות, ומגיע למינוס 8 אחרי 5 שניות")
    X, Y = g.graph(70, 260, 420, 220, "t (s)", "v (m/s)", xticks=[(t, str(t)) for t in range(1, 6)], yticks=[(v, str(v)) for v in (-8, -4, 4, 8, 12)], xmax=5.6, ymin=-9.5, ymax=13)
    g.plot(X, Y, [(0, 12), (5, -8)])
    g.guide(X, Y, 5, -8)
    return g

