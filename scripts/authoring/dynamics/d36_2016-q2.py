from mk import *
PTS = [(0.01, 0.13), (0.02, 0.16), (0.03, 0.26), (0.04, 0.44), (0.05, 0.53), (0.06, 0.56)]
n = 6; xm = sum(p[0] for p in PTS) / n; ym = sum(p[1] for p in PTS) / n
slope = sum((x - xm) * (y - ym) for x, y in PTS) / sum((x - xm) ** 2 for x, _ in PTS)

