from mk import *

def fig():
    g = Fig(560, 330, "תרשים א: שני גופים במסה M תלויים משני צדי גלגלת בחוט b, והגלגלת תלויה מהתקרה בחוט c. תרשים ב: לגוף הימני נוסף גוף במסה m בחוט d")
    for ox, extra, lab in ((140, False, "תרשים א"), (400, True, "תרשים ב")):
        g.ceiling(ox - 60, ox + 60, 20)
        g.line(ox, 20, ox, 70, width=1.5); g.text(ox + 8, 50, "c", anchor="start")
        g.pulley(ox, 90, 22)
        g.line(ox - 22, 90, ox - 22, 190, width=1.5); g.line(ox + 22, 90, ox + 22, 190, width=1.5)
        g.text(ox + 30, 150, "b", anchor="start")
        g.block(ox - 22, 205, 34, 30, "M"); g.block(ox + 22, 205, 34, 30, "M")
        if extra:
            g.line(ox + 22, 220, ox + 22, 270, width=1.5); g.text(ox + 30, 250, "d", anchor="start")
            g.block(ox + 22, 284, 28, 26, "m")
        g.heb(ox, 322, lab)
    return g

