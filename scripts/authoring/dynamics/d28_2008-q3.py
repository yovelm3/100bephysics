from mk import *

def fig():
    g = Fig(560, 260, "תרשים א: גוף 1 (0.5 קילוגרם) וגוף 2 תלויים משני צדי גלגלת בחוט b, והגלגלת תלויה מהתקרה בחוט c. כוח F1 מושך את גוף 1 כלפי מטה. תרשים ב: מהירות גוף 1 עולה מאפס ל-30 מטר לשנייה ב-6 שניות וקבועה עד 12")
    g.ceiling(60, 260, 20); g.line(160, 20, 160, 50, width=1.5); g.text(168, 40, "c", anchor="start")
    g.pulley(160, 74, 24)
    g.line(136, 74, 136, 160, width=1.5); g.line(184, 74, 184, 160, width=1.5); g.text(192, 120, "b", anchor="start")
    g.block(136, 176, 28, 32, "1"); g.block(184, 176, 28, 32, "2")
    g.text(116, 180, "m₁ = 0.5 kg", anchor="end"); g.text(204, 180, "m₂", anchor="start")
    g.arrow(136, 194, 136, 230, "F₁", lx=124, ly=226, anchor="end")
    g.heb(160, 254, "תרשים א")
    X, Y = g.graph(330, 200, 180, 140, "t (s)", "v (m/s)", xticks=[(6, "6"), (12, "12")], yticks=[(30, "30")], xmax=13, ymax=35, grid=False)
    g.plot(X, Y, [(0, 0), (6, 30), (12, 30)]); g.guide(X, Y, 6, 30)
    g.heb(420, 254, "תרשים ב")
    return g

