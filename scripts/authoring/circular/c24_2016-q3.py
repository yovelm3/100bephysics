import math

def fig():
    g = Fig(560, 330, "מסלול ABCD: רבע מעגל חלק ABC ברדיוס R, A בגובה המרכז, ו-C בתחתית; קטע CD אופקי מחוספס. B על הקשת בזווית תטא. וארבעה גרפים I עד IV של אנרגיה כפונקציה של זמן")
    O = (240, 30); R = 150
    g.path(f"M {O[0] - R},{O[1]} A {R} {R} 0 0 0 {O[0]},{O[1] + R}", width=3)
    g.line(O[0], O[1] + R, O[0] + 260, O[1] + R, width=3)
    g.dot(*O); g.line(*O, O[0] - R, O[1], stroke="var(--d-dim)", width=1, dash="3 3"); g.line(*O, O[0], O[1] + R, stroke="var(--d-dim)", width=1, dash="3 3")
    th = math.radians(35); B = (O[0] - R * math.cos(th), O[1] + R * math.sin(th))
    g.line(*O, *B, stroke="var(--d-dim)", width=1, dash="3 3"); g.angle(*O, 30, 180 + 0, 215, "θ", lr=44)
    g.block(O[0] - R + 12, O[1] + 6, 18, 14, "m"); g.text(O[0] - R - 8, O[1] + 4, "A", anchor="end")
    g.dot(*B); g.text(B[0] - 10, B[1], "B", anchor="end"); g.text(O[0], O[1] + R + 20, "C"); g.text(O[0] + 220, O[1] + R + 20, "D")
    g.text(O[0] + 10, O[1] + R / 2, "R", anchor="start")
    for i, (lab, kw) in enumerate([("IV", dict(fn=lambda u: 0.9 * (1 - u) ** 3)), ("III", dict(fn=lambda u: 0.9 * (1 - (1 - u) ** 2.5))), ("II", dict(pts=[(0, 0.6), (1, 0.6)])), ("I", dict(pts=[(0, 0.9), (0.8, 0)]))]):
        mini(g, 40 + i * 130, 300, 90, 60, label=lab, yl="E", **kw)
    return g

