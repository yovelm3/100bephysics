from mk import *
import math
t = math.radians(15); w = math.sqrt(10 * (math.sin(t) + 0.5 * math.cos(t)) / (0.1 * (math.cos(t) - 0.5 * math.sin(t))))

def fig():
    g = Fig(560, 260, "ציר אנכי, ומולחם אליו צינור בזווית של 75 מעלות לציר. גוף במסה m בתוך הצינור, במרחק r = 10 סנטימטר מהציר")
    g.rect(120, 20, 16, 230, fill="var(--d-fill)"); g.heb(128, 14, "ציר")
    a = math.radians(15)
    x0, y0 = 128, 200
    x1, y1 = x0 + 360 * math.cos(a), y0 - 360 * math.sin(a)
    g.line(x0, y0 - 8, x1, y1 - 8, width=2); g.line(x0, y0 + 8, x1, y1 + 8, width=2)
    bx, by = x0 + 220 * math.cos(a), y0 - 220 * math.sin(a)
    g.block(bx, by, 24, 12, "m", angle=15)
    g.angle(x0, y0, 34, 15, 90, "α", lr=48)
    g.dim(x0, 236, bx, 236, "r", offset=0)
    g.line(bx, by, bx, 240, stroke="var(--d-dim)", width=1, dash="3 3")
    return g

