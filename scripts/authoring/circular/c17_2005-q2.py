from mk import *
import math
v2_30 = 20 * (math.cos(math.radians(30)) - 0.5); T30 = 0.1 * (10 * math.cos(math.radians(30)) + v2_30 / 1)

def fig():
    g = Fig(560, 260, "מטוטלת: משקולת 100 גרם על חוט באורך 1 מטר, מתנודדת בין A ל-C, בזווית מרבית של 60 מעלות מהאנך. B הנקודה הנמוכה. ולידה שמונה חצים ממוספרים")
    O = (200, 30); L = 170
    g.ceiling(150, 250, 30); g.dot(*O)
    A = (O[0] - L * math.sin(math.radians(60)), O[1] + L * math.cos(math.radians(60))); C = (O[0] + L * math.sin(math.radians(60)), A[1])
    g.path(f"M {A[0]:.1f},{A[1]:.1f} A {L} {L} 0 0 0 {C[0]:.1f},{C[1]:.1f}", stroke="var(--d-dim)", width=1.4, dash="6 5")
    g.line(*O, *C, width=1.5); g.ball(*C, 8); g.text(C[0] + 12, C[1] + 4, "C", anchor="start")
    g.text(A[0] - 12, A[1] + 4, "A", anchor="end"); g.text(O[0], O[1] + L + 20, "B")
    g.line(*O, O[0], O[1] + L, stroke="var(--d-dim)", width=1, dash="3 3")
    g.angle(*O, 30, 270, 330, "60°", lr=46); g.text((O[0] + C[0]) / 2 + 14, (O[1] + C[1]) / 2, "1 m", cls="dim", anchor="start")
    cx, cy, r = 460, 130, 50
    angs = [90, 60, 0, -60, -90, -120, 180, 120]
    for i, d in enumerate(angs):
        ang = math.radians(d)
        g.arrow(cx, cy, cx + r * math.cos(ang), cy - r * math.sin(ang), None, width=1.8)
        g.text(cx + (r + 14) * math.cos(ang), cy - (r + 14) * math.sin(ang) + 5, str(i + 1))
    g.text(cx + 30, cy - 12, "60°", cls="dim", anchor="start"); g.text(cx - 30, cy - 12, "60°", cls="dim", anchor="end")
    return g

