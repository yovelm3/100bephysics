def fig():
    g = Fig(560, 260, "עמוד אנכי עם זרוע אופקית. בקצה הזרוע חבל שבקצהו משקולת. המערכת מסתובבת במהירות זוויתית אומגה, והחבל נוטה בזווית אלפא מהאנך. המשקולת בנקודה A")
    g.rect(150, 30, 14, 190, fill="var(--d-fill)"); g.line(157, 36, 287, 36, width=4)
    a = math.radians(25); L = 160
    ex, ey = 287 + L * math.sin(a), 36 + L * math.cos(a)
    g.line(287, 36, ex, ey, width=1.5); g.line(287, 36, 287, 200, stroke="var(--d-dim)", width=1, dash="3 3")
    g.angle(287, 36, 36, 270, 295, "α", lr=50)
    g.ball(ex, ey, 9); g.text(ex + 12, ey + 18, "A", anchor="start")
    g.add(f'<ellipse cx="157" cy="{ey:.0f}" rx="{ex - 157:.0f}" ry="30" fill="none" stroke="var(--d-dim)" stroke-width="1.4" stroke-dasharray="6 5"/>')
    g.path("M 132,110 A 26 8 0 1 0 182,110", stroke="var(--d-body)", width=2, arrow=True); g.text(124, 108, "ω", anchor="end")
    g.heb(150, 20, "עמוד אנכי"); g.heb(230, 24, "זרוע אופקית")
    return g

