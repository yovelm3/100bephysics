    g.dot(*O); g.text(O[0] + 6, O[1] - 10, "O₁ O₂", anchor="start")
    g.line(O[0] - 120, O[1], O[0], O[1], width=1.5); g.ball(O[0] - 120, O[1], 9); g.text(O[0] - 136, O[1] + 4, "A", anchor="end")
    g.line(O[0], O[1], O[0], O[1] + 120, width=1.5); g.ball(O[0], O[1] + 128, 11); g.text(O[0], O[1] + 158, "B")
