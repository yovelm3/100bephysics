def path_fig():
    g = Fig(560, 280, "תרשים התשובה: המעגל האנכי, והמסלול של הגוף אחרי שהחוט נקרע בנקודה D: קו ישר אנכי מ-D כלפי מטה עד הקרקע")
    O = (280, 125); R = 95
    g.circle(*O, R, fill="none", stroke="var(--d-line)", dash="5 4")
    g.dot(*O); g.text(O[0] + 10, O[1] - 6, "O", anchor="start")
    D = (O[0] + R, O[1])
    g.dot(*D); g.text(D[0] + 14, D[1] + 5, "D")
    g.ground(60, 500, 255)
    g.line(D[0], D[1], D[0], 255, stroke="var(--d-ask)", width=3, dash="7 5")
    g.arrow(D[0] + 30, D[1] + 10, D[0] + 30, D[1] + 60, "v", lx=D[0] + 44, ly=D[1] + 40, anchor="start")
    g.heb(D[0] - 12, 215, "מסלול אנכי", anchor="end")
    return g

def body(forces, note, alt, pos):
    return lambda: fbd(forces, alt, positive=pos, body="ball", note=note)

