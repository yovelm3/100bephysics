def fig():
    g = Fig(560, 260, "גוף במסה 0.3 קילוגרם קשור לחוט באורך 0.8 מטר ונע במעגל אנכי סביב O. A הנקודה הנמוכה, B הגבוהה, C ו-D בקצוות הקוטר האופקי. הגוף נע בכיוון השעון")
    O = (280, 125); R = 95
    g.circle(*O, R, fill="none", stroke="var(--d-line)", dash="5 4")
    g.dot(*O); g.text(O[0] + 10, O[1] - 6, "O", anchor="start")
    for p, t, dx, dy in (((O[0], O[1] + R), "A", 0, 24), ((O[0], O[1] - R), "B", 0, -10), ((O[0] - R, O[1]), "C", -14, 5), ((O[0] + R, O[1]), "D", 14, 5)):
        g.dot(*p); g.text(p[0] + dx, p[1] + dy, t)
    g.line(*O, O[0] - 67, O[1] + 67, width=1.5); g.ball(O[0] - 67, O[1] + 67, 8)
    g.text(O[0] - 46, O[1] + 26, "0.8 m", cls="dim", rotate=-45)
    for a in (135, 45, -45):  # clockwise, as in the original drawing
        r = math.radians(a); d = math.radians(a - 12)
        x1, y1 = O[0] + R * math.cos(r), O[1] - R * math.sin(r); x2, y2 = O[0] + R * math.cos(d), O[1] - R * math.sin(d)
        g.line(x1, y1, x2, y2, width=1.8, arrow=True)
    g.ground(60, 500, 240)
    return g

