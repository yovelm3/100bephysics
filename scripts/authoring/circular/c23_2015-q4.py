from mk import *
import math

def fig():
    g = Fig(560, 260, "מטוטלת: כדור קטן במסה m על חוט באורך L. נקודה 3 היא נקודת שיווי המשקל, ונקודה 1 בגובה h מעליה. חמש נקודות 1 עד 5 על המסלול. הכדור פוגע ברצפה במרחק D")
    O = (220, 20); L = 160
    g.ceiling(150, 290, 20); g.dot(*O)
    for i, ang in enumerate([-40, -20, 0, 20, 40]):
        a = math.radians(ang); x, y = O[0] + L * math.sin(a), O[1] + L * math.cos(a)
        g.line(*O, x, y, stroke="var(--d-dim)" if i else "var(--d-line)", width=1 if i else 1.5, dash="4 3" if i else None)
        g.circle(x, y, 7, fill="var(--d-label)" if i == 0 else "#ffffff", stroke="var(--d-line)"); g.text(x + (12 if ang >= 0 else -12), y + 4, str(i + 1), anchor="start" if ang >= 0 else "end")
    y1 = O[1] + L * math.cos(math.radians(40)); y3 = O[1] + L
    g.line(80, y1, 220, y1, stroke="var(--d-dim)", width=1, dash="3 3"); g.line(80, y3, 220, y3, stroke="var(--d-dim)", width=1, dash="3 3")
    g.dim(90, y1, 90, y3, "h"); g.text(150, 100, "L", anchor="end")
    g.ground(60, 520, 240)
    g.dim(220, 222, 440, 222, "D", offset=0); g.ball(440, 232, 8)
    return g

