v = math.sqrt(0.4 * 10 * 80); th = math.degrees(math.atan(v * v / 800))

def fig():
    g = Fig(560, 560, "תרשים א: מכונית במעקם אופקי ברדיוס 80 מטר. תרשים ב: חתך של כביש מוגבה בזווית תטא, והמכונית עליו. תרשים ג: ארבעה סרטוטי כוחות על מכונית בכביש המוגבה (הצד הגבוה משמאל): בכולם המשקל כלפי מטה והנורמלי מאונך לכביש; כוח החיכוך: 1 במורד השיפוע, 2 במעלה השיפוע, 3 אופקי ימינה, 4 אופקי שמאלה")
    g.path("M 30,150 A 200 90 0 0 1 250,60", width=2); g.path("M 70,170 A 200 90 0 0 1 260,95", width=2)
    g.path("M 50,160 A 200 90 0 0 1 255,78", stroke="var(--d-dim)", width=1.5, dash="8 6")
    g.rect(150, 95, 30, 16, fill="var(--d-body)", rx=4); g.heb(150, 210, "תרשים א")
    t = math.radians(22)
    g.poly([(320, 190), (540, 190), (540, 190 - 220 * math.tan(t))], fill="var(--d-fill)")
    g.angle(320, 190, 50, 0, 22, "θ", lr=64)
    g.block(440, 190 - 120 * math.tan(t) - 12, 46, 22, None, angle=22)
    g.heb(430, 228, "תרשים ב")
    # תרשים ג: four force diagrams on the banked road (high side on the left), as in the original
    tt = math.radians(25)
    opts = [("1", "down"), ("2", "up"), ("3", "right"), ("4", "left")]
    for i, (lab, fd) in enumerate(opts):
        bx = 420 - (i % 2) * 300; by = 330 + (i // 2) * 150
        g.line(bx - 110, by - 110 * math.tan(tt) * 0 - 50, bx + 80, by + 40, width=1.6)
        g.line(bx - 60, by + 40, bx + 80, by + 40, width=1.6)
        c = (bx - 10 - 5, by - 2.6 - 11)
        g.block(c[0], c[1], 50, 20, None, angle=-25)
        g.dot(*c)
        g.arrow(c[0], c[1], c[0], c[1] + 52, None, width=1.6); g.text(c[0] + 6, c[1] + 50, "mg", cls="dim", anchor="start")
        g.arrow(c[0], c[1], c[0] + 50 * math.sin(tt), c[1] - 50 * math.cos(tt), None, width=1.6); g.text(c[0] + 26, c[1] - 46, "N", cls="dim", anchor="start")
        u = {"down": (math.cos(tt), math.sin(tt)), "up": (-math.cos(tt), -math.sin(tt)), "right": (1, 0), "left": (-1, 0)}[fd]
        g.arrow(c[0], c[1], c[0] + 52 * u[0], c[1] + 52 * u[1], None, width=1.6); g.text(c[0] + 62 * u[0], c[1] + 62 * u[1] - 6, "f", cls="dim")
        g.text(bx + 110, by, lab)
    g.heb(280, 548, "תרשים ג")
    return g

