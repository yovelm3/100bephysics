from mk import *

def fig():
    g = Fig(560, 280, "מטוטלת קונית: גוף m בקצה חוט באורך ℓ שקשור לנקודה A, ונע במעגל אופקי. החוט נוטה בזווית אלפא מהאנך, ו-h המרחק מ-A למרכז המעגל")
    A = (330, 30)
    g.dot(*A); g.text(A[0], A[1] - 10, "A")
    g.add(f'<ellipse cx="{A[0]}" cy="230" rx="170" ry="26" fill="none" stroke="var(--d-dim)" stroke-width="1.5" stroke-dasharray="5 4"/>')
    g.line(*A, 175, 238, width=1.5); g.ball(172, 240, 8); g.text(160, 262, "m")
    g.line(*A, A[0], 230, stroke="var(--d-dim)", width=1.2, dash="4 3")
    g.dim(A[0] + 30, A[1], A[0] + 30, 230, "h")
    g.angle(*A, 50, 233, 270, "α", lr=64)
    g.text(238, 120, "ℓ", anchor="end")
    return g

