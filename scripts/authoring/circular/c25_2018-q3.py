def accel_fig():
    g = Fig(480, 300, "תרשים התשובה: הקשת CG, שהמרכז שלה מעליה, ובנקודה D חץ כתום של התאוצה הכוללת. החץ נוטה למעלה, אל מרכז הקשת, וקדימה, בכיוון התנועה במורד")
    O = (240, 30); R = 200
    a0, a1 = math.radians(220), math.radians(320)
    pts = [(O[0] + R * math.cos(a0 + (a1 - a0) * k / 40), O[1] - R * math.sin(a0 + (a1 - a0) * k / 40)) for k in range(41)]
    g.path("M " + " L ".join(f"{x:.1f},{y:.1f}" for x, y in pts), width=3)
    g.dot(*O); g.text(O[0] + 8, O[1] + 4, "O", anchor="start")
    aD = math.radians(245); D = (O[0] + R * math.cos(aD), O[1] - R * math.sin(aD))
    g.dot(*D); g.text(D[0] - 10, D[1] + 16, "D", anchor="end")
    g.text(pts[0][0] - 8, pts[0][1] + 4, "C", anchor="end"); g.text(pts[-1][0] + 8, pts[-1][1] + 4, "G", anchor="start")
    g.line(*O, *D, stroke="var(--d-dim)", width=1, dash="4 3")
    rx, ry = (O[0] - D[0]) / R, (O[1] - D[1]) / R          # towards the centre
    tx, ty = -ry, rx                                        # tangent, direction of motion (down the slope, to the right)
    if tx < 0: tx, ty = -tx, -ty
    ax, ay = 0.8 * rx + 0.6 * tx, 0.8 * ry + 0.6 * ty
    g.arrow(D[0], D[1], D[0] + 60 * ax, D[1] + 60 * ay, color="var(--d-ask)", width=2.8)
    g.text(D[0] + 70 * ax + 6, D[1] + 70 * ay, "a", cls="label", color="var(--d-ask)", anchor="start")
    g.arrow(D[0], D[1], D[0] + 50 * tx, D[1] + 50 * ty, color="var(--d-label)", width=2)
    g.text(D[0] + 58 * tx, D[1] + 58 * ty + 14, "v", cls="label")
    return g

