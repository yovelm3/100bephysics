from mk import *
import math

def arrows8(g, cx, cy, r=34, labels=("1", "2", "3", "4", "5", "6", "7", "8"), cls="label"):
    for i, lab in enumerate(labels):
        ang = math.radians(90 - 45 * i)
        x, y = cx + r * math.cos(ang), cy - r * math.sin(ang)
        g.arrow(cx, cy, x, y, None, width=1.8)
        g.text(cx + (r + 12) * math.cos(ang), cy - (r + 12) * math.sin(ang) + 5, lab, cls=cls)

