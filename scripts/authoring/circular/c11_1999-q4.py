    g.ball(40, 40, 6); g.text(30, 36, "A", anchor="end")
    g.dim(20, 40, 20, 250, "H")
    g.text(150, 272, "C"); g.text(110, 240, "B", anchor="end"); g.text(196, 236, "D", anchor="start")
    g.circle(150, 205, 45, fill="none", stroke="var(--d-dim)", dash="4 4"); g.text(150, 200, "R", cls="dim")
