from mk import *

def fig():
    g = Fig(560, 260, "מסילה חסרת חיכוך ABCDEFG עם לולאה מעגלית CDEF ברדיוס 0.4 מטר. C הנקודה הנמוכה ו-E העליונה, D ו-F בקצות הקוטר האופקי. A בגובה 1.2 מטר מעל C")
    C = (280, 230); r = 80; Oc = (C[0], C[1] - r)
    g.path(f"M 60,20 Q 120,240 {C[0]},{C[1]} Q 440,240 500,60", width=3)
    g.circle(*Oc, r, fill="none", stroke="var(--d-line)", width=3)
    g.dot(*Oc)
    for (x, y, t, dx, dy) in ((60, 20, "A", -10, 4), (80, 110, "B", -12, 4), (C[0], C[1], "C", 0, 22), (C[0] + r, Oc[1], "D", 14, 5), (C[0], C[1] - 2 * r, "E", 0, -10), (C[0] - r, Oc[1], "F", -14, 5), (500, 60, "G", 12, 0)):
        g.dot(x, y); g.text(x + dx, y + dy, t)
    g.ball(64, 26, 6)
    return g

