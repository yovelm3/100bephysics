from mk import *
import math

def fig():
    g = Fig(560, 260, "מתקן: עמוד אנכי וזרוע אופקית. בקצה הזרוע חבל, ובקצהו כיסא עם מאזני קפיץ ונער. המערכת מסתובבת במעגל אופקי, והחבל נוטה בזווית אלפא מהאנך")
    g.rect(150, 30, 12, 200, fill="var(--d-fill)")
    g.line(156, 36, 276, 36, width=3)
    a = math.radians(30); L = 130
    ex, ey = 276 + L * math.sin(a), 36 + L * math.cos(a)
    g.line(276, 36, ex, ey, width=1.5); g.line(276, 36, 276, 130, stroke="var(--d-dim)", width=1, dash="3 3")
    g.angle(276, 36, 34, 270, 300, "α", lr=48)
    g.poly([(ex - 18, ey), (ex + 18, ey), (ex + 22, ey + 22), (ex - 22, ey + 22)], fill="var(--d-fill)")
    g.person(ex, ey + 2, 0.55)
    g.add(f'<ellipse cx="156" cy="{ey + 12:.0f}" rx="230" ry="34" fill="none" stroke="var(--d-dim)" stroke-width="1.4" stroke-dasharray="6 5"/>')
    return g

