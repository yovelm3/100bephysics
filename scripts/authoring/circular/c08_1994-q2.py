def answer_fig():
    import math
    g = fig()
    g.alt = "תרשים התשובה: המסלול, ובנקודות B, C, E ו-F חץ שחור של המהירות בכיוון התנועה וחץ כתום של התאוצה והכוח השקול. בנקודה B התאוצה קדימה, בנקודה C אחורה, ובנקודות E ו-F פנימה אל O וקצת קדימה"
    sx = lambda x: (x - 30) * 0.82 + 20
    sy = lambda y: (y - 40) * 0.82 + 20
    O = (505, 205)
    def arrows(x, y, t, a, va=40, aa=38, side=(0, 0)):
        X, Y = sx(x) + side[0], sy(y) + side[1]
        g.arrow(X, Y, X + va * t[0], Y + va * t[1], color="var(--d-label)", width=2.2)
        g.text(X + (va + 10) * t[0], Y + (va + 10) * t[1] + 5, "v", cls="label")
        X2, Y2 = sx(x) - side[0], sy(y) - 2.2 * side[1]
        g.arrow(X2, Y2, X2 + aa * a[0], Y2 + aa * a[1], color="var(--d-ask)", width=2.6)
        g.text(X2 + (aa + 12) * a[0], Y2 + (aa + 12) * a[1] + 5, "a", cls="label", color="var(--d-ask)")
    arrows(160, 340, (1, 0), (1, 0), 40, 30, side=(0, -12))
    arrows(472, 340, (1, 0), (-1, 0), 40, 30, side=(0, -12))
    for x, y in ((597, 303), (582, 90)):
        rx, ry = x - O[0], y - O[1]; L = math.hypot(rx, ry)
        rhat = (rx / L, ry / L); that = (ry / L, -rx / L)
        ax, ay = -0.85 * rhat[0] + 0.5 * that[0], -0.85 * rhat[1] + 0.5 * that[1]; La = math.hypot(ax, ay)
        arrows(x, y, that, (ax / La, ay / La))
    return g

