def fig():
    g = Fig(560, 320, "מקומות של גוף במרווחי זמן קבועים על משטח אופקי: קטע ישר ABCD, ואחריו קשת מעגלית DEFG סביב O")
    sx = lambda x: (x - 30) * 0.82 + 20
    sy = lambda y: (y - 40) * 0.82 + 20
    for i in range(0, 20):
        g.line(sx(25 + i * 34), sy(40), sx(25 + i * 34), sy(380), stroke="var(--d-hatch)", width=0.7)
    for j in range(0, 11):
        g.line(sx(25), sy(40 + j * 34), sx(670), sy(40 + j * 34), stroke="var(--d-hatch)", width=0.7)
    g.line(sx(60), sy(340), sx(505), sy(340), width=2)
    g.path(f"M {sx(505)},{sy(340)} A {138*0.82} {138*0.82} 0 1 0 {sx(368)},{sy(228)}", width=2)
    for x, y in PTS:
        g.circle(sx(x), sy(y), 4.5, fill="var(--d-label)")
    g.dot(sx(505), sy(205), 3); g.text(sx(492), sy(212), "O", anchor="end")
