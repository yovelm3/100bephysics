from mk import *
import math

def fig():
    g = Fig(560, 300, "כדור במסה m בקצה חוט באורך L שקשור לנקודה O, משוחרר כשהחוט אופקי. מסמר C נמצא L/2 מתחת ל-O. אחרי שהחוט נתקל במסמר הכדור נע במעגל סביב C, והחוט יוצר זווית אלפא עם OC")
    O = (180, 50); L = 200; C = (O[0], O[1] + L / 2)
    g.dot(*O); g.text(O[0] - 10, O[1] - 6, "O", anchor="end")
    g.line(*O, O[0] + L, O[1], width=1.5, dash="5 4"); g.ball(O[0] + L, O[1], 8); g.text(O[0] + L + 14, O[1] + 4, "m", anchor="start")
    g.dim(O[0], O[1] - 20, O[0] + L, O[1] - 20, "L")
    g.path(f"M {O[0] + L},{O[1]} A {L} {L} 0 0 1 {O[0]},{O[1] + L}", stroke="var(--d-dim)", width=1.4, dash="6 5")
    g.path(f"M {O[0]},{O[1] + L} A {L/2} {L/2} 0 0 1 {O[0] - 70},{C[1] - 70}", stroke="var(--d-dim)", width=1.4, dash="6 5")
    g.line(*O, *C, width=1.5); g.dot(*C); g.text(C[0] - 10, C[1] + 16, "C", anchor="end")
    a = math.radians(40)
    bx, by = C[0] - (L / 2) * math.sin(a), C[1] - (L / 2) * math.cos(a)
    g.line(*C, bx, by, width=1.5); g.ball(bx, by, 8)
    g.angle(*C, 26, 90, 130, "α", lr=40)
    g.text(O[0] + 12, (O[1] + C[1]) / 2 + 4, "L/2", anchor="start")
    return g

E(id="bagrut-1996-q3", year=1996, label="1996 שאלה 3", topic="circular", sub="circ-vertical", diff=4, fig=fig,
  stem=r"כדור קטן שמסתו $m$ קשור לקצה חוט שאורכו $L$. קצהו השני של החוט קשור בנקודה קבועה $O$. הכדור משוחרר ממצב שבו החוט אופקי וישר. כאשר החוט מגיע למצב אנכי, הוא נתקל במסמר שנמצא במרחק $L/2$ מתחת לנקודה $O$, בנקודה $C$. מסמנים ב-$\alpha$ את הזווית שהחוט יוצר עם $OC$, כשהכדור נע סביב $C$. המסמר ניצב למישור התנועה של החוט.",
  parts=[
    P("א", r"מהו גודל המהירות של הכדור כאשר החוט יוצר זווית $\alpha$ עם $OC$? בטא את תשובתך באמצעות $L$ ו-$\alpha$.", OPEN, ["principle", "algebra"], [
        S(r"גובה הכדור", r"הכדור סובב סביב $C$ ברדיוס $L/2$. ביחס לגובה ההתחלתי (גובה $O$) הוא נמוך ב-", r"\Delta h = \frac{L}{2} - \frac{L}{2}\cos\alpha"),
        S(r"שימור אנרגיה", r"אין חיכוך, והחוט לא מבצע עבודה", r"v^2 = 2g\Delta h = gL(1 - \cos\alpha)"),
    ], r"$v = \sqrt{gL(1 - \cos\alpha)}$", key=r"√(gℓ(1−cosα))"),
    P("ב", r"הראה כי ברגע שבו המתיחות בחוט מתאפסת, מתקיים $\cos\alpha = 2/3$.", OPEN, ["fbd", "principle", "algebra"], [
        S(r"הכוחות בכיוון הרדיאלי (כלפי $C$)", r"המתיחות ורכיב הכובד $mg\cos\alpha$", r"T + mg\cos\alpha = \frac{m v^2}{L/2}"),
        S(r"מציבים $T = 0$ ואת $v^2$", r"המסה מתבטלת", r"g\cos\alpha = 2g(1 - \cos\alpha)"),
        S(r"פותרים", r"מעבירים אגפים", r"3\cos\alpha = 2 \Rightarrow \cos\alpha = \frac{2}{3}"),
    ], r"$\cos\alpha = 2/3$"),
    P("ג", r"מה תהיה צורת המסלול של הכדור כל עוד המתיחות בחוט היא אפס (קו ישר, מעגל, פרבולה, אחר)? נמק.", choice(["קו ישר", "מעגל", "פרבולה", "אחר"], 2), ["principle"], [
        S(r"רק כובד", r"החוט רפוי, ולכדור יש מהירות משופעת", r"\vec a = \vec g"),
    ], r"פרבולה: זריקה משופעת", key=r"פרבולה"),
  ],
  concepts=["מעגל אנכי", "שימור אנרגיה", "מתיחות מתאפסת", "זריקה משופעת"],
  summary=r"מטוטלת שהחוט שלה נתקל במסמר: מהירות לפי הזווית, היכן החוט מתרופף, ומה המסלול אחר כך.")
