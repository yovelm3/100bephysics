    g.dot(ex, ey); g.dot(mx, ey)
    g.line(ex, ey, mx, ey, width=1.2)
    g.dim(ex, ey - 12, ex + 55, ey - 12, "R", ext=False, label_dy=-2)
    g.dot(ex + 55, ey); g.text(ex + 66, ey - 8, "A", anchor="start")
