from mk import *
x = 0.9 * 60
Ep = lambda r: -(1 / r + 1 / (81 * (60 - r)))
k = Ep(x) - Ep(1)

def fig():
    g = Fig(560, 200, "כדור הארץ (מסה M1, רדיוס R) משמאל והירח (מסה M2) מימין. הנקודה A על פני כדור הארץ, על הקו המחבר את המרכזים. הנקודה O על הקו, קרובה לירח. המרחק בין המרכזים d")
    ex, ey, mx = 110, 95, 470
    g.circle(ex, ey, 55, fill="var(--d-fill)", stroke="var(--d-line)"); g.heb(ex, ey - 66, "כדור הארץ"); g.text(ex - 10, ey + 78, "M₁")
    g.circle(mx, ey, 18, fill="var(--d-fill)", stroke="var(--d-line)"); g.heb(mx, ey - 28, "הירח"); g.text(mx + 12, ey + 40, "M₂")
    g.dot(ex, ey); g.dot(mx, ey)
    g.line(ex, ey, mx, ey, width=1.2)
    g.dim(ex, ey - 12, ex + 55, ey - 12, "R", ext=False, label_dy=-2)
    g.dot(ex + 55, ey); g.text(ex + 66, ey - 8, "A", anchor="start")
    ox = ex + 0.9 * (mx - ex); g.dot(ox, ey); g.text(ox, ey - 12, "O")
    g.dim(ex, ey + 22, mx, ey + 22, "d", ext=False, label_dy=6)
    return g

