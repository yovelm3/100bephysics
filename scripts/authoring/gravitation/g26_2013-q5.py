def orbit_fig():
    g = Fig(460, 280, "המסלול האליפטי עם החצים: בנקודות B ו-D המהירות משיקה למסלול בכיוון השעון. בנקודה A התאוצה מכוונת אל כדור הארץ. בנקודות C ו-E הכוח השקול מכוון אל כדור הארץ")
    cx, cy, ax, by = 230, 140, 170, 100
    g.path(f"M {cx - ax} {cy} A {ax} {by} 0 1 0 {cx + ax} {cy} A {ax} {by} 0 1 0 {cx - ax} {cy}", width=2)
    c = math.sqrt(ax ** 2 - by ** 2); ex, ey = cx + c, cy
    g.circle(ex, ey, 16, fill="var(--d-fill)", stroke="var(--d-line)")
    P_ = lambda t: (cx + ax * math.cos(math.radians(t)), cy - by * math.sin(math.radians(t)))
    for lab, t, dx, dy in [("A", 0, 14, 5), ("B", 270, 0, 22), ("C", 180, -14, 5), ("D", 130, -12, -8), ("E", 92, 0, -12)]:
        x, y = P_(t); g.dot(x, y); g.text(x + dx, y + dy, lab)
    def tang(t, L, lab, ldx, ldy):
        x, y = P_(t); tx, ty = ax * math.sin(math.radians(t)), by * math.cos(math.radians(t)); n = math.hypot(tx, ty)
        g.arrow(x, y, x + L * tx / n, y + L * ty / n, lab, lx=x + L * tx / n + ldx, ly=y + L * ty / n + ldy, color="var(--d-ask)")
    def toE(t, L, lab, ldx, ldy):
        x, y = P_(t); dx, dy = ex - x, ey - y; n = math.hypot(dx, dy)
        g.arrow(x, y, x + L * dx / n, y + L * dy / n, lab, lx=x + L * dx / n + ldx, ly=y + L * dy / n + ldy)
    tang(270, 55, "v", -4, 16); tang(130, 50, "v", 4, -8)
    toE(0, 15, "a", 10, -12); toE(180, 50, "F", 0, -10); toE(92, 50, "F", 12, 0)
    return g

