from mk import *
import math
M = 7.3e5; F = 1.16e7; g0 = 10
a = F / M - g0

def fig():
    g = Fig(460, 280, "מסלול אליפטי סביב כדור הארץ. כדור הארץ קרוב לקצה הימני של האליפסה, ליד הנקודה A. הנקודות על המסלול: A בקצה הימני, B בתחתית, C בקצה השמאלי, D למעלה משמאל, E למעלה באמצע")
    cx, cy, ax, by = 230, 140, 170, 100
    g.path(f"M {cx - ax} {cy} A {ax} {by} 0 1 0 {cx + ax} {cy} A {ax} {by} 0 1 0 {cx - ax} {cy}", width=2)
    c = math.sqrt(ax ** 2 - by ** 2)
    g.circle(cx + c, cy, 16, fill="var(--d-fill)", stroke="var(--d-line)"); g.heb(cx + c - 10, cy - 26, "כדור הארץ")
    P_ = lambda t: (cx + ax * math.cos(math.radians(t)), cy - by * math.sin(math.radians(t)))
    for lab, t, dx, dy in [("A", 0, 14, 5), ("B", 270, 0, 22), ("C", 180, -14, 5), ("D", 130, -12, -8), ("E", 92, 0, -12)]:
        x, y = P_(t); g.dot(x, y); g.text(x + dx, y + dy, lab)
    return g

