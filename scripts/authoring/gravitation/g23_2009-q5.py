from mk import *
import math
G = 6.67e-11; H = 1e7; R = H; r = R + H; T = 150 * 60
M = 4 * math.pi ** 2 * r ** 3 / (G * T ** 2); gs = G * M / R ** 2

def rocket(g, cx, cy, ang, flame, k=1.7):
    c, s = math.cos(math.radians(ang)), math.sin(math.radians(ang))
    P_ = lambda u, v: (cx + k * (u * c - v * s), cy + k * (u * s + v * c))
    g.poly([P_(18, 0), P_(6, -7), P_(-12, -7), P_(-12, 7), P_(6, 7)], fill="var(--d-fill)", stroke="var(--d-line)", width=1.6)
    if flame:
        for v in (-5, 0, 5):
            a, b = P_(-14, v), P_(-28, v * 1.6)
            g.line(a[0], a[1], b[0], b[1], width=1.4, stroke="var(--d-accent, var(--d-body))")

def fig():
    g = Fig(620, 380, "למעלה: ארבעה תרשימים של חללית מעל כוכב לכת. א: חרטום כלפי מעלה והסילון כלפי הכוכב. ב: חרטום כלפי הכוכב והסילון כלפי מעלה. ג: החללית אופקית והסילון הצידה. ד: חרטום כלפי מעלה, המנוע כבוי. למטה: מרכז הכוכב O, רדיוס R, החללית בגובה H מעל פני הכוכב, ושני קווים משיקים ביניהם זווית של 60 מעלות")
    labels = ["א", "ב", "ג", "ד"]
    setups = [(-90, True), (90, True), (180, True), (-90, False)]
    for i, (lab, (ang, fl)) in enumerate(zip(labels, setups)):
        x = 545 - i * 150
        g.circle(x, 145, 34, fill="var(--d-fill)", stroke="var(--d-line)")
        rocket(g, x, 50 if ang != 90 else 58, ang, fl)
        g.heb(x, 200, lab)
    ox, oy, Rp = 130, 290, 55
    g.circle(ox, oy, Rp, fill="var(--d-fill)", stroke="var(--d-line)"); g.dot(ox, oy); g.text(ox - 12, oy + 5, "O")
    sx = ox + 2 * Rp + 140
    tx, ty = ox + Rp / 2, oy - Rp * math.sqrt(3) / 2
    for sgn in (1, -1):
        g.line(sx, oy, ox + (tx - ox), oy + sgn * (ty - oy), width=1.1, dash="5 4")
    g.line(ox, oy, ox + Rp, oy, width=1.6); g.text(ox + Rp / 2, oy - 7, "R")
    g.dim(ox + Rp, oy + 20, sx, oy + 20, "H", ext=False)
    g.angle(sx, oy, 26, 150, 210, "60°", lr=40)
    rocket(g, sx + 32, oy, 0, False, k=1.2)
    g.heb(sx + 26, oy + 30, "חללית"); g.heb(ox, oy + Rp + 20, "כוכב לכת")
    return g

