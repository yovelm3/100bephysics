from mk import *
import math
G = 6.67e-11; k = 3.44
Ms = 4 * math.pi ** 2 / (G * k * 1e-19)
pts = [(0.006, 0.02), (0.05, 0.17), (0.25, 0.86), (0.84, 2.89), (1.83, 6.3)]

def fig():
    g = Fig(620, 300, "שמאל: גרף T בריבוע כפונקציה של r בשלישית לחמישה כוכבי לכת, נקודות על קו ישר מהראשית עד בערך 1.83 ו-6.3. ימין: השמש, לוויין וכדור הארץ על קו אחד, המרחק בין הלוויין לכדור הארץ x")
    X, Y = g.graph(60, 260, 280, 220, "r³ (10³⁸ m³)", "T² (10¹⁹ s²)", xticks=[(v, f"{v:g}") for v in (0.5, 1, 1.5, 2)], yticks=[(v, str(v)) for v in range(1, 8)], xmax=2.1, ymax=7.3)
    g.plot(X, Y, [(0, 0), (1.95, 1.95 * k)])
    for a, b in pts: g.circle(X(a), Y(b), 4.5, fill="var(--d-accent, var(--d-body))")
    cy = 150; sx, ex = 420, 590; satx = 545
    g.circle(sx, cy, 16, fill="var(--d-fill)", stroke="var(--d-line)"); g.heb(sx, cy + 36, "שמש")
    g.circle(ex, cy, 8); g.heb(ex, cy + 28, "ארץ")
    g.ball(satx, cy, r=5); g.heb(satx - 6, cy - 16, "לוויין")
    g.line(sx + 18, cy, satx - 7, cy, width=1.3, dash="5 4")
    g.dim(satx, cy + 50, ex, cy + 50, "x", ext=False)
    return g

