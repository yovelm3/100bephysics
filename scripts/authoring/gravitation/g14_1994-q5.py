def gr_fig():
    g = Fig(440, 270, "גרף תאוצת הנפילה כפונקציה של המרחק מהמרכז: עקומה יורדת מעשרה מטר לשנייה בריבוע ברדיוס אחד, לשניים וחצי בשני רדיוסים")
    X, Y = g.graph(70, 230, 330, 190, "r", "g (m/s²)", xticks=[(1, "R"), (1.5, "1.5R"), (2, "2R")], yticks=[(2.5, "2.5"), (5, "5"), (7.5, "7.5"), (10, "10")], xmax=2.2, ymax=11)
    g.curve(X, Y, lambda r: 10 / r ** 2, 1, 2)
    for r, a in ((1, 10), (2, 2.5)): g.line(X(r), Y(a), X(r), Y(0), stroke="var(--d-dim)", width=1, dash="3 3")
    return g

