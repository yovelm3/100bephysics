from mk import *
import math
G = 6.67e-11; M = 5.98e24; R = 6.37e6; T = 86400
r = (G * M * T ** 2 / (4 * math.pi ** 2)) ** (1 / 3); h = r - R; a = G * M / r ** 2
r2 = r / 2 ** (2 / 3); h2 = r2 - R

def fig():
    g = Fig(420, 290, "כדור הארץ ועליו נקודה A. הלוויין עמוס 1 במסלול מעגלי, תמיד מעל הנקודה A")
    cx, cy = 210, 150
    g.circle(cx, cy, 120, fill="none", stroke="var(--d-line)", width=1.3, dash="6 5")
    g.circle(cx, cy, 50, fill="var(--d-fill)", stroke="var(--d-line)"); g.heb(cx, cy + 6, "כדור הארץ")
    g.dot(cx, cy - 50); g.text(cx + 12, cy - 54, "A", anchor="start")
    g.ball(cx, cy - 120, r=8); g.heb(cx + 52, cy - 124, "עמוס 1")
    g.line(cx, cy - 58, cx, cy - 110, width=1.2, dash="4 4"); g.text(cx - 10, cy - 82, "h", anchor="end")
    return g

