from mk import *
import math
GM = 10 * 6.4e6 ** 2; r = 6.4e6; v = math.sqrt(GM / (4 * r)); vm = 500 * v / 100; Q = 0.5 * 500 * v * v + 0.5 * 100 * vm * vm; vf = math.sqrt(2 * GM * (1 / r - 1 / (4 * r)))

def fig():
    g = Fig(560, 260, "כדור הארץ ברדיוס r, ולוויין m1 במסלול מעגלי בגובה h = 3r מעל פני כדור הארץ. בנקודה A מתנגש בו מטאוריט m2")
    g.circle(280, 200, 50, fill="var(--d-fill)", stroke="var(--d-line)"); g.line(280, 200, 315, 165, width=1.2); g.text(306, 190, "r", cls="dim", anchor="start")
    g.path("M 90,200 A 190 190 0 0 1 470,200", stroke="var(--d-dim)", width=1.4, dash="6 5")
    g.dot(280, 10); g.text(270, 14, "A", anchor="end"); g.ball(290, 10, 5); g.text(300, 14, "m₁", anchor="start")
    g.ball(430, 10, 5); g.text(440, 14, "m₂", anchor="start"); g.arrow(422, 10, 360, 10, None)
    g.dim(260, 150, 260, 10, "h", offset=0)
    return g

E(id="bagrut-1981-q2", year=1981, label="1981 שאלה 2", topic="gravitation", sub="grav-orbits", diff=4, fig=fig,
  stem=r"לוויין בעל מסה $m_1 = 500\,\text{kg}$ מקיף את כדור הארץ במסלול מעגלי, בגובה $h = 3r$ מעל פני כדור הארץ (הנח כי $r$, רדיוס כדור הארץ, שווה ל-$6400\,\text{km}$). בהיות הלוויין מעל הנקודה $A$ על פני כדור הארץ, מתנגש בו מטאוריט בעל מסה $m_2 = 100\,\text{kg}$. כתוצאה מכך נעצרים הלוויין והמטאוריט להרף עין, ולאחר מכן מתחילים שניהם ליפול יחדיו בכיוון אנכי כלפי מטה. ($g = 10\,\text{m/s}^2$ על פני כדור הארץ.)",
  parts=[
    P("א", r"מה הייתה מהירות הלוויין לפני שהתנגש בו המטאוריט?", num(v, "m/s"), ["principle"], [
        S(r"כבידה כוח צנטריפטלי", r"רדיוס המסלול $4r$", r"v = \sqrt{\frac{GM}{4r}}"),
        S(r"$GM = gr^2$", r"מציבים", r"v = \sqrt{\frac{g r}{4}} = \sqrt{\frac{10 \cdot 6.4 \times 10^6}{4}} = 4 \times 10^3\,\text{m/s}"),
    ], r"$4 \times 10^3\,\text{m/s}$", key=r"4×10^3 m/s"),
    P("ב", r"מה הייתה מהירות המטאוריט ברגע ההתנגשות?", num(vm, "m/s"), ["principle"], [
        S(r"שימור תנע", r"אחרי ההתנגשות הם עומדים להרף עין: התנע הכולל אפס", r"500 \cdot 4000 = 100\,v_m"),
        S(r"פותרים", r"מחלקים ב-100", r"v_m = 2 \times 10^4\,\text{m/s}"),
    ], r"$2 \times 10^4\,\text{m/s}$, נגד כיוון הלוויין", key=r"2×10^4 m/s"),
    P("ג", r"מהי כמות החום (בג'אולים) שהתפתחה כתוצאה מההתנגשות?", num(Q, "J"), ["principle"], [
        S(r"כל האנרגיה הקינטית", r"אחרי ההתנגשות הם עומדים", r"Q = \tfrac{1}{2} \cdot 500 \cdot (4 \times 10^3)^2 + \tfrac{1}{2} \cdot 100 \cdot (2 \times 10^4)^2 = 2.4 \times 10^{10}\,\text{J}"),
    ], r"$2.4 \times 10^{10}\,\text{J}$", key=r"2.4×10^10 J"),
    P("ד", r"באיזו מהירות היו הלוויין והמטאוריט מגיעים ופוגעים בנקודה $A$, אילו בשעת נפילתם לא היו פועלים עליהם כוחות חיכוך (כמו התנגדות האוויר)?", num(vf, "m/s"), ["principle", "algebra"], [
        S(r"שימור אנרגיה בשדה כבידה", r"מנוחה במרחק $4r$ עד פני כדור הארץ", r"\tfrac{1}{2}v^2 = GM\left(\frac{1}{r} - \frac{1}{4r}\right) = \frac{3GM}{4r}"),
        S(r"מציבים", r"GM = gr²", r"v = \sqrt{\frac{3 g r}{2}} = \sqrt{9.6 \times 10^7} \approx 9.8 \times 10^3\,\text{m/s}"),
    ], r"$\approx 9.8 \times 10^3\,\text{m/s}$", key=r"≈9.8×10^3 m/s"),
  ],
  concepts=["מהירות מסלולית", "התנגשות פלסטית", "אנרגיה פוטנציאלית כבידתית", "GM = gR²"],
  summary=r"לוויין ומטאוריט שעוצרים זה את זה: מהירויות לפני, חום שנוצר, ומהירות הפגיעה בקרקע מאנרגיה בשדה כבידה.",
  review="הוספתי g = 10 על פני כדור הארץ (במפתח התשובות מתאימות ל-GM = gR²).")
