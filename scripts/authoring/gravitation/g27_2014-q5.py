    g = Fig(560, 230, "שמאל: מאדים ושני מסלולים מעגליים, של פובוס (פנימי) ושל דימוס (חיצוני). ימין: חללית מרחפת 20 מטר מעל קרקע מאדים, ומטאורואיד נע אופקית לעברה במהירות 12.5 מטר לשנייה")
