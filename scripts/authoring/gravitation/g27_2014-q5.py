from mk import *
import math
G = 6.67e-11; Tp = 0.3189; rp = 9.377e6; Td = 1.262; R = 3.4e6
rD = rp * (Td / Tp) ** (2 / 3)
M = 4 * math.pi ** 2 * rp ** 3 / (G * (Tp * 86400) ** 2)
u = 1.3 * 12.5 / (53 + 1.3)
gm = G * M / R ** 2; t = math.sqrt(2 * 20 / gm)

