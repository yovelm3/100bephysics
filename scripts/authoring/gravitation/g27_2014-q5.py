    g.circle(cx, cy, 26, fill="var(--d-fill)", stroke="var(--d-line)"); g.heb(cx, cy + 5, "מאדים")
    g.circle(cx, cy, 52, fill="none", stroke="var(--d-line)", width=1.1, dash="4 4"); g.ball(cx + 52, cy, r=4); g.heb(cx + 62, cy + 4, "פובוס", anchor="start")
    g.circle(cx, cy, 96, fill="none", stroke="var(--d-line)", width=1.1, dash="4 4"); g.ball(cx - 68, cy - 68, r=4); g.heb(cx - 70, cy - 82, "דימוס")
