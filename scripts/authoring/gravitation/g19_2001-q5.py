import math
k = 600; c = k / (4 * math.pi ** 2); m = 30.7
Mf = lambda T: c * T * T - m

def fig():
    g = Fig(560, 260, "גרף כיול: מסת האסטרונאוט M כפונקציה של זמן המחזור T של התנודות: עקומה עולה מאפס בערך ב-1.42 שניות עד 100 קילוגרם בערך ב-2.95 שניות")
    X, Y = g.graph(80, 230, 380, 190, "T (s)", "M (kg)", xticks=[(v, f"{v:g}") for v in (0.5, 1, 1.5, 2, 2.5, 3)], yticks=[(v, str(v)) for v in (20, 40, 60, 80, 100)], xmax=3.3, ymax=105)
    g.curve(X, Y, Mf, math.sqrt(m / c), math.sqrt((m + 102) / c))
    return g

