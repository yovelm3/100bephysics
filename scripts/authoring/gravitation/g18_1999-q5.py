R = [4.22, 6.71, 10.7, 18.83]; T = [1.77, 3.55, 7.16, 16.69]
Tn = 1.77 * (1 / 4.22) ** 1.5

def fig():
    g = Fig(560, 170, "טבלה: רדיוס המסלול (ביחידות של 10 בחזקת 5 קילומטר) וזמן המחזור (בימים) של ארבעה ירחים של צדק")
    x0, y0 = 60, 20
    g.rect(x0, y0, 440, 130, fill="none", width=1.2)
    for r in range(1, 5): g.line(x0, y0 + r * 26, x0 + 440, y0 + r * 26, width=0.8)
    g.line(x0 + 140, y0, x0 + 140, y0 + 130, width=0.8); g.line(x0 + 300, y0, x0 + 300, y0 + 130, width=0.8)
    g.heb(x0 + 70, y0 + 18, "הירח"); g.text(x0 + 220, y0 + 18, "r (10⁵ km)"); g.heb(x0 + 370, y0 + 18, "זמן מחזור (ימים)")
    for i, (r, t) in enumerate(zip(R, T)):
        y = y0 + 26 * (i + 1) + 18
        g.heb(x0 + 70, y, f"ירח {i + 1}"); g.text(x0 + 220, y, f"{r:g}", cls="dim"); g.text(x0 + 370, y, f"{t:g}", cls="dim")
    return g

